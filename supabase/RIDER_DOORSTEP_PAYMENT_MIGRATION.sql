CREATE OR REPLACE FUNCTION public.claim_rider_handover_code(
  p_order_id BIGINT,
  p_rider_phone TEXT,
  p_code_hash TEXT,
  p_expires_at TIMESTAMPTZ
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  claimed_order_id BIGINT;
BEGIN
  IF p_code_hash !~ '^[0-9a-f]{64}$'
     OR p_expires_at <= now()
     OR p_expires_at > now() + INTERVAL '15 minutes' THEN
    RAISE EXCEPTION 'Handover code details are invalid.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.orders o
    JOIN public.rider_status r ON r.rider_phone = p_rider_phone
    WHERE o.id = p_order_id
      AND o.rider_phone = p_rider_phone
      AND o.status = 'Out for Delivery'
      AND r.verification_status = 'Verified'
  ) THEN
    RAISE EXCEPTION 'This rider cannot issue a handover code for this order.';
  END IF;

  INSERT INTO public.rider_handover_codes (
    order_id, rider_phone, code_hash, status, expires_at, attempt_count,
    provider_message_id, verified_at, consumed_at, error_message, created_at, updated_at
  )
  VALUES (
    p_order_id, p_rider_phone, p_code_hash, 'sending', p_expires_at, 0,
    NULL, NULL, NULL, NULL, now(), now()
  )
  ON CONFLICT (order_id) DO UPDATE SET
    rider_phone = EXCLUDED.rider_phone,
    code_hash = EXCLUDED.code_hash,
    status = 'sending',
    expires_at = EXCLUDED.expires_at,
    attempt_count = 0,
    provider_message_id = NULL,
    verified_at = NULL,
    consumed_at = NULL,
    error_message = NULL,
    created_at = now(),
    updated_at = now()
  WHERE public.rider_handover_codes.rider_phone IS DISTINCT FROM EXCLUDED.rider_phone
     OR public.rider_handover_codes.status IN ('failed', 'expired', 'locked')
     OR public.rider_handover_codes.expires_at <= now()
     OR (
       public.rider_handover_codes.status = 'sending'
       AND public.rider_handover_codes.updated_at < now() - INTERVAL '2 minutes'
     )
  RETURNING order_id INTO claimed_order_id;

  IF claimed_order_id IS NOT NULL THEN
    UPDATE public.orders
    SET rider_handover_verified_at = NULL
    WHERE id = p_order_id;
  END IF;
  RETURN claimed_order_id IS NOT NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.verify_rider_handover_code(
  p_order_id BIGINT,
  p_rider_phone TEXT,
  p_code_hash TEXT
)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  target_code public.rider_handover_codes%ROWTYPE;
  next_attempt_count INTEGER;
BEGIN
  SELECT * INTO target_code
  FROM public.rider_handover_codes
  WHERE order_id = p_order_id
  FOR UPDATE;

  IF NOT FOUND OR target_code.rider_phone IS DISTINCT FROM p_rider_phone THEN
    RETURN 'invalid';
  END IF;
  IF target_code.status IN ('verified', 'consumed') THEN
    RETURN 'verified';
  END IF;
  IF target_code.status <> 'sent' OR target_code.expires_at <= now() THEN
    UPDATE public.rider_handover_codes
    SET status = CASE WHEN expires_at <= now() THEN 'expired' ELSE status END,
        updated_at = now()
    WHERE order_id = p_order_id;
    RETURN 'expired';
  END IF;

  IF target_code.code_hash IS DISTINCT FROM p_code_hash THEN
    next_attempt_count := target_code.attempt_count + 1;
    UPDATE public.rider_handover_codes
    SET attempt_count = next_attempt_count,
        status = CASE WHEN next_attempt_count >= 5 THEN 'locked' ELSE status END,
        updated_at = now()
    WHERE order_id = p_order_id;
    RETURN CASE WHEN next_attempt_count >= 5 THEN 'locked' ELSE 'invalid' END;
  END IF;

  UPDATE public.rider_handover_codes
  SET status = 'verified',
      verified_at = now(),
      updated_at = now()
  WHERE order_id = p_order_id;
  UPDATE public.orders
  SET rider_handover_verified_at = now()
  WHERE id = p_order_id
    AND rider_phone = p_rider_phone
    AND status = 'Out for Delivery';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Order is no longer available for handover.';
  END IF;
  RETURN 'verified';
END;
$$;

CREATE OR REPLACE FUNCTION public.complete_rider_delivery(
  p_order_id BIGINT,
  p_rider_phone TEXT,
  p_customer_id_verified BOOLEAN
)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  target_order public.orders%ROWTYPE;
  target_code public.rider_handover_codes%ROWTYPE;
  blocking_issue BOOLEAN;
BEGIN
  SELECT * INTO target_order
  FROM public.orders
  WHERE id = p_order_id
  FOR UPDATE;

  IF NOT FOUND OR target_order.rider_phone IS DISTINCT FROM p_rider_phone THEN
    RAISE EXCEPTION 'Order is not assigned to this rider.';
  END IF;
  IF target_order.status = 'Delivered' THEN
    RETURN 'Delivered';
  END IF;
  IF target_order.status <> 'Out for Delivery' THEN
    RAISE EXCEPTION 'Delivery cannot be completed from the current status.';
  END IF;
  IF p_customer_id_verified IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'Customer ID must be checked before handover.';
  END IF;
  IF target_order.rider_handover_verified_at IS NULL THEN
    RAISE EXCEPTION 'Customer handover code has not been verified.';
  END IF;

  SELECT * INTO target_code
  FROM public.rider_handover_codes
  WHERE order_id = p_order_id
  FOR UPDATE;
  IF NOT FOUND
     OR target_code.rider_phone IS DISTINCT FROM p_rider_phone
     OR target_code.status NOT IN ('verified', 'consumed') THEN
    RAISE EXCEPTION 'Customer handover code has not been verified.';
  END IF;

  SELECT EXISTS (
    SELECT 1
    FROM public.delivery_events
    WHERE order_id = p_order_id
      AND to_status IN (
        'Issue reported: No valid ID',
        'Issue reported: Possible underage customer',
        'Issue reported: Customer appears intoxicated',
        'Issue reported: Customer refused handover'
      )
  ) INTO blocking_issue;
  IF blocking_issue THEN
    RAISE EXCEPTION 'Handover is blocked because a safety issue was reported.';
  END IF;

  IF lower(coalesce(target_order.payment_method, '')) = 'paystack' THEN
    IF target_order.payment_verified_at IS NULL
       AND NOT EXISTS (
         SELECT 1
         FROM public.rider_delivery_payment_attempts
         WHERE order_id = p_order_id
           AND rider_phone = p_rider_phone
           AND status = 'paid'
           AND amount_ksh = pg_catalog.round(target_order.total_price)::BIGINT
       ) THEN
      RAISE EXCEPTION 'Payment has not been confirmed.';
    END IF;
  ELSIF NOT EXISTS (
    SELECT 1
    FROM public.rider_delivery_payment_attempts
    WHERE order_id = p_order_id
      AND rider_phone = p_rider_phone
      AND status = 'paid'
      AND amount_ksh = pg_catalog.round(target_order.total_price)::BIGINT
  ) THEN
    RAISE EXCEPTION 'Record the confirmed cash or electronic payment before completing delivery.';
  END IF;

  UPDATE public.rider_handover_codes
  SET status = 'consumed',
      consumed_at = COALESCE(consumed_at, now()),
      updated_at = now()
  WHERE order_id = p_order_id;

  RETURN public.advance_rider_delivery(
    p_order_id,
    p_rider_phone,
    'Delivered',
    target_order.delivery_pin,
    true
  );
END;
$$;

