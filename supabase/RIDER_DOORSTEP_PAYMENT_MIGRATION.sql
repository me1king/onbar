CREATE OR REPLACE FUNCTION public.reset_rider_handover_on_reassignment()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NEW.rider_phone IS DISTINCT FROM OLD.rider_phone
     OR (NEW.status = 'Dispatched' AND OLD.status IS DISTINCT FROM NEW.status) THEN
    NEW.rider_handover_verified_at := NULL;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.invalidate_rider_handover_on_reassignment()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NEW.rider_phone IS DISTINCT FROM OLD.rider_phone
     OR NEW.status = 'Paid' THEN
    UPDATE public.rider_handover_codes
    SET code_hash = NULL,
        status = 'expired',
        verified_at = NULL,
        consumed_at = NULL,
        updated_at = now()
    WHERE order_id = NEW.id
      AND status <> 'consumed';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS orders_reset_rider_handover ON public.orders;
CREATE TRIGGER orders_reset_rider_handover
  BEFORE UPDATE OF status, rider_phone ON public.orders
  FOR EACH ROW
  EXECUTE FUNCTION public.reset_rider_handover_on_reassignment();

DROP TRIGGER IF EXISTS orders_invalidate_rider_handover ON public.orders;
CREATE TRIGGER orders_invalidate_rider_handover
  AFTER UPDATE OF status, rider_phone ON public.orders
  FOR EACH ROW
  EXECUTE FUNCTION public.invalidate_rider_handover_on_reassignment();

