CREATE TABLE IF NOT EXISTS public.rider_handover_codes (
  order_id BIGINT PRIMARY KEY REFERENCES public.orders(id) ON DELETE RESTRICT,
  rider_phone TEXT NOT NULL REFERENCES public.rider_status(rider_phone) ON DELETE RESTRICT,
  code_hash TEXT,
  status TEXT NOT NULL CHECK (status IN ('sending', 'sent', 'failed', 'expired', 'verified', 'locked', 'consumed')),
  expires_at TIMESTAMPTZ NOT NULL,
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  provider_message_id TEXT,
  verified_at TIMESTAMPTZ,
  consumed_at TIMESTAMPTZ,
  error_message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

