-- RPC: Metric Incrementor
CREATE OR REPLACE FUNCTION public.increment_session_metric(sess_id TEXT, metric_name TEXT, inc_val INTEGER)
RETURNS VOID AS $$
BEGIN
    EXECUTE format('UPDATE public.customer_sessions SET %I = %I + $1, updated_at = now() WHERE id = $2', metric_name, metric_name)
    USING inc_val, sess_id;
END;
$$ LANGUAGE plpgsql;

-- RPC: Behavioral Event Batch Logger
CREATE OR REPLACE FUNCTION public.log_event_batch(p_events JSONB)
RETURNS VOID AS $$
BEGIN
    INSERT INTO public.session_forensics (session_id, action_type, page_url, metadata, timestamp)
    SELECT
        (e->>'session_id')::text,
        (e->>'action_type')::text,
        (e->>'page_url')::text,
        (e->'metadata')::jsonb,
        (e->>'timestamp')::timestamptz
    FROM jsonb_array_elements(p_events) AS e;
END;
$$ LANGUAGE plpgsql;

-- RPC: Active Time Tracker
CREATE OR REPLACE FUNCTION public.increment_session_active_time(sess_id TEXT, inc_active_ms INTEGER, inc_dwell_ms INTEGER)
RETURNS VOID AS $$
BEGIN
    UPDATE public.customer_sessions
    SET
        total_active_time_sec = total_active_time_sec + (inc_active_ms / 1000),
        total_dwell_time_sec = total_dwell_time_sec + (inc_dwell_ms / 1000),
        updated_at = now()
    WHERE id = sess_id;
END;
$$ LANGUAGE plpgsql;

