CREATE OR REPLACE FUNCTION public.allocate_paid_order_items_after_confirmation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    item_record RECORD;
BEGIN
    IF NOT (
        (
            lower(coalesce(NEW.payment_method, '')) = 'cod'
            AND lower(coalesce(NEW.status, '')) IN ('pending', 'placed', 'confirmed')
        )
        OR (
            lower(coalesce(NEW.status, '')) = 'paid'
            AND NEW.payment_verified_at IS NOT NULL
            AND lower(coalesce(NEW.payment_method, '')) = 'paystack'
        )
    )
       OR (
           OLD.status IS NOT DISTINCT FROM NEW.status
           AND OLD.payment_verified_at IS NOT DISTINCT FROM NEW.payment_verified_at
       ) THEN
        RETURN NEW;
    END IF;

    FOR item_record IN
        SELECT id, quantity
        FROM public.order_items
        WHERE order_id = NEW.id
        ORDER BY id
    LOOP
        BEGIN
            UPDATE public.order_items
            SET quantity = item_record.quantity
            WHERE id = item_record.id;
        EXCEPTION WHEN OTHERS THEN
            RAISE WARNING 'Merchant allocation for paid order item % was not completed: %',
                item_record.id, SQLERRM;
        END;
    END LOOP;
    RETURN NEW;
END;
$$;

