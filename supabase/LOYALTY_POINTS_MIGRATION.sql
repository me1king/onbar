CREATE OR REPLACE FUNCTION public.apply_loyalty_points(
    profile_id_input UUID,
    amount_input INTEGER,
    description_input TEXT,
    event_key_input TEXT
)
RETURNS TABLE (balance INTEGER, applied BOOLEAN)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    current_balance INTEGER;
BEGIN
    IF amount_input = 0 OR length(trim(description_input)) = 0 OR length(trim(event_key_input)) = 0 THEN
        RAISE EXCEPTION 'A non-zero amount, description, and event key are required.';
    END IF;

    SELECT p.loyalty_points
      INTO current_balance
      FROM public.profiles p
     WHERE p.id = profile_id_input
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Member profile not found.';
    END IF;

    IF EXISTS (
        SELECT 1 FROM public.loyalty_ledger l WHERE l.event_key = event_key_input
    ) THEN
        RETURN QUERY SELECT current_balance, false;
        RETURN;
    END IF;

    IF current_balance + amount_input < 0 THEN
        RAISE EXCEPTION 'Insufficient loyalty points.';
    END IF;

    UPDATE public.profiles
       SET loyalty_points = current_balance + amount_input,
           updated_at = now()
     WHERE id = profile_id_input
     RETURNING loyalty_points INTO current_balance;

    INSERT INTO public.loyalty_ledger (profile_id, amount, description, event_key)
    VALUES (profile_id_input, amount_input, trim(description_input), event_key_input);

    RETURN QUERY SELECT current_balance, true;
END;
$$;

CREATE OR REPLACE FUNCTION public.redeem_loyalty_points(
    profile_id_input UUID,
    points_input INTEGER,
    coupon_code_input TEXT,
    discount_amount_input NUMERIC
)
RETURNS TABLE (balance INTEGER)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    current_balance INTEGER;
BEGIN
    IF points_input <= 0 OR discount_amount_input <= 0 OR length(trim(coupon_code_input)) < 6 THEN
        RAISE EXCEPTION 'Invalid loyalty redemption.';
    END IF;

    SELECT p.loyalty_points
      INTO current_balance
      FROM public.profiles p
     WHERE p.id = profile_id_input
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Member profile not found.';
    END IF;
    IF current_balance < points_input THEN
        RAISE EXCEPTION 'Insufficient loyalty points.';
    END IF;

    UPDATE public.profiles
       SET loyalty_points = current_balance - points_input,
           updated_at = now()
     WHERE id = profile_id_input
     RETURNING loyalty_points INTO current_balance;

    INSERT INTO public.coupons (code, discount_percent, discount_amount, owner_profile_id, is_active)
    VALUES (upper(trim(coupon_code_input)), 0, discount_amount_input, profile_id_input, true);

    INSERT INTO public.loyalty_ledger (profile_id, amount, description, event_key)
    VALUES (
        profile_id_input,
        -points_input,
        'Redeemed ' || points_input || ' points for KSh ' || discount_amount_input || ' store credit. CODE: ' || upper(trim(coupon_code_input)),
        'redemption:' || upper(trim(coupon_code_input))
    );

    RETURN QUERY SELECT current_balance;
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_loyalty_daily_reward(
    profile_id_input UUID,
    reward_type_input TEXT,
    reward_label_input TEXT,
    reward_value_input INTEGER,
    points_awarded_input INTEGER,
    coupon_code_input TEXT DEFAULT NULL,
    coupon_discount_percent_input INTEGER DEFAULT NULL,
    coupon_discount_amount_input NUMERIC DEFAULT NULL
)
RETURNS TABLE (balance INTEGER, claimed_at TIMESTAMPTZ)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    current_balance INTEGER;
    last_claim TIMESTAMPTZ;
BEGIN
    IF reward_type_input NOT IN ('spin', 'box')
        OR length(trim(reward_label_input)) = 0
        OR reward_value_input < 0
        OR points_awarded_input < 0 THEN
        RAISE EXCEPTION 'Invalid daily reward.';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended(profile_id_input::TEXT || ':' || reward_type_input, 0));

    SELECT log.created_at
      INTO last_claim
      FROM public.daily_rewards_log log
     WHERE log.user_id = profile_id_input
       AND log.reward_type = reward_type_input
     ORDER BY log.created_at DESC
     LIMIT 1;

    IF last_claim IS NOT NULL AND last_claim > now() - interval '24 hours' THEN
        RAISE EXCEPTION 'Reward can only be claimed once every 24 hours.';
    END IF;

    SELECT p.loyalty_points
      INTO current_balance
      FROM public.profiles p
     WHERE p.id = profile_id_input
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Member profile not found.';
    END IF;

    IF coupon_code_input IS NOT NULL THEN
        IF (coupon_discount_percent_input IS NULL OR coupon_discount_percent_input NOT BETWEEN 1 AND 100)
            AND (coupon_discount_amount_input IS NULL OR coupon_discount_amount_input <= 0) THEN
            RAISE EXCEPTION 'Invalid reward voucher configuration.';
        END IF;
        INSERT INTO public.coupons (code, discount_percent, discount_amount, is_active, owner_profile_id)
        VALUES (
            upper(trim(coupon_code_input)),
            COALESCE(coupon_discount_percent_input, 0),
            COALESCE(coupon_discount_amount_input, 0),
            true,
            profile_id_input
        );
    END IF;

    INSERT INTO public.daily_rewards_log (user_id, reward_type, reward_label, reward_value)
    VALUES (profile_id_input, reward_type_input, trim(reward_label_input), reward_value_input)
    RETURNING daily_rewards_log.created_at INTO claimed_at;

    IF points_awarded_input > 0 THEN
        UPDATE public.profiles
           SET loyalty_points = current_balance + points_awarded_input,
               updated_at = now()
         WHERE id = profile_id_input
         RETURNING loyalty_points INTO current_balance;

        INSERT INTO public.loyalty_ledger (profile_id, amount, description, event_key)
        VALUES (
            profile_id_input,
            points_awarded_input,
            'Daily ' || reward_type_input || ' reward: ' || trim(reward_label_input),
            'daily:' || profile_id_input::TEXT || ':' || reward_type_input || ':' || claimed_at::TEXT
        );
    END IF;

    RETURN QUERY SELECT current_balance, claimed_at;
END;
$$;

CREATE OR REPLACE FUNCTION public.unlock_loyalty_achievement(
    profile_id_input UUID,
    achievement_key_input TEXT
)
RETURNS TABLE (unlocked BOOLEAN, points_awarded INTEGER, balance INTEGER)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    achievement_row public.achievements%ROWTYPE;
    current_balance INTEGER;
    inserted_id BIGINT;
BEGIN
    SELECT * INTO achievement_row
      FROM public.achievements
     WHERE key = achievement_key_input;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Achievement blueprint not found.';
    END IF;

    INSERT INTO public.user_achievements (user_id, achievement_key)
    VALUES (profile_id_input, achievement_key_input)
    ON CONFLICT (user_id, achievement_key) DO NOTHING
    RETURNING id INTO inserted_id;

    SELECT p.loyalty_points
      INTO current_balance
      FROM public.profiles p
     WHERE p.id = profile_id_input
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Member profile not found.';
    END IF;

    IF inserted_id IS NULL THEN
        RETURN QUERY SELECT false, 0, current_balance;
        RETURN;
    END IF;

    IF achievement_row.points_reward > 0 THEN
        UPDATE public.profiles
           SET loyalty_points = current_balance + achievement_row.points_reward,
               xp = COALESCE(xp, 0) + COALESCE(achievement_row.xp_reward, 0),
               updated_at = now()
         WHERE id = profile_id_input
         RETURNING loyalty_points INTO current_balance;

        INSERT INTO public.loyalty_ledger (profile_id, amount, description, event_key)
        VALUES (
            profile_id_input,
            achievement_row.points_reward,
            'Achievement unlocked: ' || achievement_row.label,
            'achievement:' || profile_id_input::TEXT || ':' || achievement_key_input
        );
    ELSE
        UPDATE public.profiles
           SET xp = COALESCE(xp, 0) + COALESCE(achievement_row.xp_reward, 0),
               updated_at = now()
         WHERE id = profile_id_input;
    END IF;

    RETURN QUERY SELECT true, achievement_row.points_reward, current_balance;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_loyalty_mission_event(
    profile_id_input UUID,
    mission_type_input TEXT,
    source_key_input TEXT
)
RETURNS TABLE (progress INTEGER, completed BOOLEAN, points_awarded INTEGER, balance INTEGER, applied BOOLEAN)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    mission_definition public.mission_definitions%ROWTYPE;
    current_progress INTEGER := 0;
    current_completed BOOLEAN := false;
    current_balance INTEGER;
    next_progress INTEGER;
    inserted_count INTEGER;
BEGIN
    IF profile_id_input IS NULL
        OR length(trim(mission_type_input)) = 0
        OR length(trim(source_key_input)) = 0 THEN
        RAISE EXCEPTION 'A member, mission, and verified event are required.';
    END IF;

    SELECT p.loyalty_points
      INTO current_balance
      FROM public.profiles p
     WHERE p.id = profile_id_input
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Member profile not found.';
    END IF;

    SELECT *
      INTO mission_definition
      FROM public.mission_definitions
     WHERE id = mission_type_input
       AND is_active = true;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Mission definition not found or inactive.';
    END IF;

    SELECT um.progress, um.is_completed
      INTO current_progress, current_completed
      FROM public.user_missions um
     WHERE um.user_id = profile_id_input
       AND um.mission_type = mission_type_input
     FOR UPDATE;
    current_progress := COALESCE(current_progress, 0);
    current_completed := COALESCE(current_completed, false);

    INSERT INTO public.loyalty_mission_events (user_id, mission_type, source_key)
    VALUES (profile_id_input, mission_type_input, trim(source_key_input))
    ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS inserted_count = ROW_COUNT;

    IF inserted_count = 0 OR current_completed THEN
        RETURN QUERY SELECT
            current_progress,
            current_completed,
            0,
            current_balance,
            false;
        RETURN;
    END IF;

    next_progress := LEAST(mission_definition.target_count, current_progress + 1);
    current_completed := next_progress >= mission_definition.target_count;

    INSERT INTO public.user_missions (user_id, mission_type, progress, is_completed, updated_at)
    VALUES (profile_id_input, mission_type_input, next_progress, current_completed, now())
    ON CONFLICT (user_id, mission_type) DO UPDATE
        SET progress = EXCLUDED.progress,
            is_completed = EXCLUDED.is_completed,
            updated_at = EXCLUDED.updated_at;

    IF current_completed AND mission_definition.xp_reward > 0 THEN
        SELECT result.balance
          INTO current_balance
          FROM public.apply_loyalty_points(
              profile_id_input,
              mission_definition.xp_reward,
              'Completed mission: ' || mission_definition.label,
              'mission:' || profile_id_input::TEXT || ':' || mission_type_input
          ) AS result;
    END IF;

    RETURN QUERY SELECT
        next_progress,
        current_completed,
        CASE WHEN current_completed THEN mission_definition.xp_reward ELSE 0 END,
        current_balance,
        true;
END;
$$;

