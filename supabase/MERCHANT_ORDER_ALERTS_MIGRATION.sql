-- Apply after MERCHANT_OPERATIONS_MIGRATION.sql and DISPATCH_MIGRATION.sql.
-- Private service-role storage for merchant push devices, alert recipients, and delivery logs.
BEGIN;

CREATE TABLE IF NOT EXISTS public.merchant_alert_contacts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  application_id UUID NOT NULL REFERENCES public.merchant_applications(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (char_length(trim(name)) BETWEEN 1 AND 120),
  phone TEXT NOT NULL CHECK (char_length(trim(phone)) BETWEEN 5 AND 40),
  role TEXT,
  channels TEXT[] NOT NULL DEFAULT ARRAY['push']::TEXT[]
    CHECK (channels <@ ARRAY['push', 'sms', 'voice']::TEXT[]),
  shift_start TIME NOT NULL DEFAULT '00:00',
  shift_end TIME NOT NULL DEFAULT '23:59',
  language TEXT NOT NULL DEFAULT 'en' CHECK (language IN ('en', 'sw')),
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (application_id, phone)
);

CREATE TABLE IF NOT EXISTS public.merchant_push_subscriptions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  application_id UUID NOT NULL REFERENCES public.merchant_applications(id) ON DELETE CASCADE,
  contact_id UUID NOT NULL REFERENCES public.merchant_alert_contacts(id) ON DELETE CASCADE,
  endpoint TEXT NOT NULL UNIQUE,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  user_agent TEXT,
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.merchant_order_alert_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT REFERENCES public.orders(id) ON DELETE SET NULL,
  application_id UUID NOT NULL REFERENCES public.merchant_applications(id) ON DELETE CASCADE,
  contact_id UUID REFERENCES public.merchant_alert_contacts(id) ON DELETE SET NULL,
  channel TEXT NOT NULL CHECK (channel IN ('push', 'sms', 'voice', 'timeout')),
  step TEXT NOT NULL CHECK (step IN ('push', 'sms_20s', 'voice_60s', 'timeout_90s', 'test')),
  recipient_key TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('sending', 'sent', 'delivered', 'opened', 'accepted', 'failed', 'no_device', 'stopped', 'missed')),
  provider_id TEXT,
  error TEXT,
  attempt_count INTEGER NOT NULL DEFAULT 1,
  sent_at TIMESTAMPTZ,
  delivered_at TIMESTAMPTZ,
  opened_at TIMESTAMPTZ,
  accepted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (order_id, application_id, channel, step, recipient_key)
);

CREATE TABLE IF NOT EXISTS public.merchant_alert_worker_heartbeats (
  worker_key TEXT PRIMARY KEY,
  last_seen_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS merchant_alert_contacts_application_idx
  ON public.merchant_alert_contacts (application_id, active);
CREATE INDEX IF NOT EXISTS merchant_push_subscriptions_contact_idx
  ON public.merchant_push_subscriptions (contact_id, last_seen_at DESC);
CREATE INDEX IF NOT EXISTS merchant_order_alert_log_order_idx
  ON public.merchant_order_alert_log (order_id, created_at DESC);
CREATE INDEX IF NOT EXISTS merchant_order_alert_log_application_idx
  ON public.merchant_order_alert_log (application_id, created_at DESC);
CREATE INDEX IF NOT EXISTS merchant_order_alert_log_provider_idx
  ON public.merchant_order_alert_log (provider_id)
  WHERE provider_id IS NOT NULL;

ALTER TABLE public.merchant_alert_contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.merchant_push_subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.merchant_order_alert_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.merchant_alert_worker_heartbeats ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.merchant_alert_contacts, public.merchant_push_subscriptions, public.merchant_order_alert_log
  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.merchant_alert_worker_heartbeats FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.merchant_alert_contacts, public.merchant_push_subscriptions, public.merchant_order_alert_log
  TO service_role;
GRANT ALL ON public.merchant_alert_worker_heartbeats TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.merchant_order_alert_log_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.respond_merchant_order_alert(
  p_order_id BIGINT,
  p_application_id UUID,
  p_actor TEXT,
  p_response TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  target_order public.orders%ROWTYPE;
BEGIN
  IF p_response NOT IN ('accepted', 'rejected') THEN
    RAISE EXCEPTION 'Order response must be accepted or rejected';
  END IF;
  SELECT * INTO target_order
  FROM public.orders
  WHERE id = p_order_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Order not found';
  END IF;
  IF lower(coalesce(target_order.status, '')) <> 'paid'
    OR target_order.payment_verified_at IS NULL
    OR lower(coalesce(target_order.payment_method, '')) <> 'paystack' THEN
    RAISE EXCEPTION 'Only a verified paid order can be accepted';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.merchant_applications application
    WHERE application.id = p_application_id AND application.status = 'approved'
  ) THEN
    RAISE EXCEPTION 'An approved merchant is required to accept this order';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.order_items item
    JOIN public.merchant_order_item_trace trace ON trace.order_item_id = item.id
    JOIN public.merchant_product_batches batch ON batch.id = trace.batch_id
    WHERE item.order_id = p_order_id AND batch.application_id = p_application_id
  ) THEN
    RAISE EXCEPTION 'Order is not allocated to this merchant';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.merchant_fulfillment_events
    WHERE order_id = p_order_id AND application_id = p_application_id
      AND event_type IN ('accepted', 'rejected')
  ) THEN
    RETURN false;
  END IF;

  INSERT INTO public.merchant_fulfillment_events (
    order_id, application_id, event_type, actor, details
  ) VALUES (
    p_order_id, p_application_id, p_response, p_actor,
    jsonb_build_object('source', 'order_alert')
  );
  UPDATE public.merchant_order_alert_log
  SET status = CASE WHEN p_response = 'accepted' THEN 'accepted' ELSE 'stopped' END,
      accepted_at = CASE WHEN p_response = 'accepted' THEN now() ELSE accepted_at END
  WHERE order_id = p_order_id
    AND application_id = p_application_id
    AND status IN ('sent', 'delivered', 'opened');
  IF p_response = 'rejected' THEN
    PERFORM public.retry_paid_order_merchant_allocation(p_order_id, p_actor);
  END IF;
  RETURN true;
END;
$$;

CREATE OR REPLACE FUNCTION public.accept_merchant_order_alert(
  p_order_id BIGINT,
  p_application_id UUID,
  p_actor TEXT
)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT public.respond_merchant_order_alert(p_order_id, p_application_id, p_actor, 'accepted');
$$;

CREATE OR REPLACE FUNCTION public.expire_merchant_order_alert(
  p_order_id BIGINT,
  p_application_id UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  target_order public.orders%ROWTYPE;
  redistribution JSONB;
BEGIN
  SELECT * INTO target_order
  FROM public.orders
  WHERE id = p_order_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'order_not_found');
  END IF;
  IF lower(coalesce(target_order.status, '')) <> 'paid'
    OR target_order.payment_verified_at IS NULL
    OR target_order.rider_phone IS NOT NULL THEN
    RETURN jsonb_build_object('status', 'order_not_open');
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.merchant_fulfillment_events
    WHERE order_id = p_order_id AND application_id = p_application_id
      AND event_type IN ('accepted', 'rejected')
  ) THEN
    RETURN jsonb_build_object('status', 'already_answered');
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.order_items item
    JOIN public.merchant_order_item_trace trace ON trace.order_item_id = item.id
    JOIN public.merchant_product_batches batch ON batch.id = trace.batch_id
    WHERE item.order_id = p_order_id AND batch.application_id = p_application_id
  ) THEN
    RETURN jsonb_build_object('status', 'not_allocated');
  END IF;

  INSERT INTO public.merchant_fulfillment_events (
    order_id, application_id, event_type, actor, details
  ) VALUES (
    p_order_id, p_application_id, 'rejected', 'order-alert-timeout',
    jsonb_build_object('source', 'order_alert', 'reason', 'No response within 90 seconds')
  );

  redistribution := public.retry_paid_order_merchant_allocation(
    p_order_id,
    'order-alert-timeout'
  );
  UPDATE public.merchant_order_alert_log
  SET status = 'missed'
  WHERE order_id = p_order_id
    AND application_id = p_application_id
    AND step = 'timeout_90s'
    AND status IN ('sending', 'sent', 'delivered');

  RETURN jsonb_build_object('status', 'missed', 'redistribution', redistribution);
END;
$$;

REVOKE ALL ON FUNCTION public.respond_merchant_order_alert(BIGINT, UUID, TEXT, TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.accept_merchant_order_alert(BIGINT, UUID, TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.expire_merchant_order_alert(BIGINT, UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.respond_merchant_order_alert(BIGINT, UUID, TEXT, TEXT) TO service_role;
GRANT EXECUTE ON FUNCTION public.accept_merchant_order_alert(BIGINT, UUID, TEXT) TO service_role;
GRANT EXECUTE ON FUNCTION public.expire_merchant_order_alert(BIGINT, UUID) TO service_role;

NOTIFY pgrst, 'reload schema';
COMMIT;
