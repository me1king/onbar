-- Link merchant support requests to the authenticated user and approved business.
-- Apply after MERCHANT_OPERATIONS_MIGRATION.sql and the support ticket schema.

DO $$
BEGIN
    IF to_regclass('public.support_tickets') IS NULL THEN
        RAISE EXCEPTION 'Merchant support history requires public.support_tickets.'
            USING HINT = 'Apply the core support ticket migration first.';
    END IF;
END;
$$;

ALTER TABLE public.support_tickets
    ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS merchant_application_id UUID
        REFERENCES public.merchant_applications(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS support_tickets_merchant_history_idx
    ON public.support_tickets (user_id, merchant_application_id, created_at DESC)
    WHERE merchant_application_id IS NOT NULL;

DO $$
DECLARE
    ticket_id_type TEXT;
BEGIN
    SELECT format_type(attribute.atttypid, attribute.atttypmod)
    INTO ticket_id_type
    FROM pg_catalog.pg_attribute AS attribute
    WHERE attribute.attrelid = 'public.support_tickets'::regclass
      AND attribute.attname = 'id'
      AND attribute.attnum > 0
      AND NOT attribute.attisdropped;

    IF ticket_id_type IS NULL THEN
        RAISE EXCEPTION 'Merchant support history requires an id column on public.support_tickets.';
    END IF;

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS public.merchant_support_messages (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ticket_id %s NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
            sender_role TEXT NOT NULL CHECK (sender_role IN ('merchant', 'admin')),
            sender_user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
            sender_name TEXT NOT NULL CHECK (char_length(trim(sender_name)) BETWEEN 1 AND 120),
            body TEXT NOT NULL CHECK (char_length(trim(body)) BETWEEN 1 AND 4000),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )
    $ddl$, ticket_id_type);
END;
$$;

CREATE INDEX IF NOT EXISTS merchant_support_messages_ticket_created_idx
    ON public.merchant_support_messages (ticket_id, created_at, id);

ALTER TABLE public.merchant_support_messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.merchant_support_messages FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.merchant_support_messages TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.merchant_support_messages_id_seq TO service_role;

NOTIFY pgrst, 'reload schema';
