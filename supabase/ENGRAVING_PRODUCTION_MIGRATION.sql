BEGIN;

ALTER TABLE public.products
    ADD COLUMN IF NOT EXISTS engraving_enabled BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS engraving_fee NUMERIC(10, 2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS gift_packaging_fee NUMERIC(10, 2) NOT NULL DEFAULT 150;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'products_engraving_fee_nonnegative'
          AND conrelid = 'public.products'::regclass
    ) THEN
        ALTER TABLE public.products
            ADD CONSTRAINT products_engraving_fee_nonnegative CHECK (engraving_fee >= 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'products_gift_packaging_fee_nonnegative'
          AND conrelid = 'public.products'::regclass
    ) THEN
        ALTER TABLE public.products
            ADD CONSTRAINT products_gift_packaging_fee_nonnegative CHECK (gift_packaging_fee >= 0);
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.engraving_jobs (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_item_id BIGINT NOT NULL UNIQUE REFERENCES public.order_items(id) ON DELETE CASCADE,
    approved_snapshot JSONB NOT NULL,
    snapshot_hash TEXT NOT NULL CHECK (snapshot_hash ~ '^[0-9a-f]{64}$'),
    status TEXT NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'engraved', 'quality_checked', 'packed', 'dispatched')),
    due_date DATE,
    updated_by TEXT,
    approved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS engraving_jobs_status_due_created_idx
    ON public.engraving_jobs (status, due_date, created_at);

CREATE TABLE IF NOT EXISTS public.engraving_job_status_history (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    engraving_job_id BIGINT NOT NULL REFERENCES public.engraving_jobs(id) ON DELETE CASCADE,
    from_status TEXT,
    to_status TEXT NOT NULL,
    changed_by TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.protect_engraving_snapshot_and_audit_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.approved_snapshot IS DISTINCT FROM NEW.approved_snapshot
       OR OLD.snapshot_hash IS DISTINCT FROM NEW.snapshot_hash
       OR OLD.approved_at IS DISTINCT FROM NEW.approved_at
       OR OLD.order_item_id IS DISTINCT FROM NEW.order_item_id THEN
        RAISE EXCEPTION 'The customer-approved engraving snapshot cannot be changed.';
    END IF;

    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO public.engraving_job_status_history (
            engraving_job_id, from_status, to_status, changed_by
        ) VALUES (
            OLD.id, OLD.status, NEW.status, NEW.updated_by
        );
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS engraving_job_snapshot_and_status_audit ON public.engraving_jobs;
CREATE TRIGGER engraving_job_snapshot_and_status_audit
    BEFORE UPDATE ON public.engraving_jobs
    FOR EACH ROW EXECUTE FUNCTION public.protect_engraving_snapshot_and_audit_status();

ALTER TABLE public.engraving_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.engraving_job_status_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.engraving_jobs, public.engraving_job_status_history FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.engraving_jobs, public.engraving_job_status_history TO service_role;
REVOKE ALL ON FUNCTION public.protect_engraving_snapshot_and_audit_status() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.protect_engraving_snapshot_and_audit_status() TO service_role;

COMMIT;
