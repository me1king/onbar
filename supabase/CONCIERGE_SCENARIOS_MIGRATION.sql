CREATE TABLE IF NOT EXISTS public.concierge_scenarios (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    scenario_key TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    triggers TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    replies JSONB NOT NULL DEFAULT '{}'::JSONB,
    mode TEXT NOT NULL DEFAULT 'exact' CHECK (mode IN ('exact', 'guided')),
    action TEXT NOT NULL DEFAULT 'none' CHECK (action IN ('none', 'support')),
    conditions JSONB NOT NULL DEFAULT '{}'::JSONB,
    chips TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'testing', 'live')),
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
    used_count BIGINT NOT NULL DEFAULT 0 CHECK (used_count >= 0),
    updated_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS concierge_scenarios_status_updated_idx
    ON public.concierge_scenarios (status, updated_at DESC);

CREATE TABLE IF NOT EXISTS public.concierge_scenario_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id UUID NOT NULL REFERENCES public.concierge_scenarios(id) ON DELETE CASCADE,
    version INTEGER NOT NULL,
    snapshot JSONB NOT NULL,
    updated_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (scenario_id, version)
);

CREATE TABLE IF NOT EXISTS public.concierge_unmatched_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message TEXT NOT NULL CHECK (char_length(message) BETWEEN 1 AND 500),
    status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'reviewed', 'converted')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS concierge_unmatched_questions_status_created_idx
    ON public.concierge_unmatched_questions (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.concierge_rate_limits (
    identity_hash TEXT PRIMARY KEY CHECK (identity_hash ~ '^[0-9a-f]{64}$'),
    window_started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    request_count INTEGER NOT NULL DEFAULT 0 CHECK (request_count >= 0)
);

ALTER TABLE public.concierge_scenarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.concierge_scenario_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.concierge_unmatched_questions ENABLE ROW LEVEL SECURITY;
