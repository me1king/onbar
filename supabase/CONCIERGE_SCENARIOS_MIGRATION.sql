CREATE OR REPLACE FUNCTION public.allow_concierge_request(
    p_identity_hash TEXT,
    p_max_requests INTEGER DEFAULT 12,
    p_window_seconds INTEGER DEFAULT 3600
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    current_count INTEGER;
BEGIN
    IF p_identity_hash !~ '^[0-9a-f]{64}$'
       OR p_max_requests < 1 OR p_max_requests > 60
       OR p_window_seconds < 60 OR p_window_seconds > 86400 THEN
        RAISE EXCEPTION 'Invalid concierge rate-limit parameters.';
    END IF;

    INSERT INTO public.concierge_rate_limits (identity_hash, window_started_at, request_count)
    VALUES (p_identity_hash, now(), 1)
    ON CONFLICT (identity_hash) DO UPDATE
    SET window_started_at = CASE
            WHEN public.concierge_rate_limits.window_started_at <= now() - make_interval(secs => p_window_seconds)
                THEN now()
            ELSE public.concierge_rate_limits.window_started_at
        END,
        request_count = CASE
            WHEN public.concierge_rate_limits.window_started_at <= now() - make_interval(secs => p_window_seconds)
                THEN 1
            ELSE public.concierge_rate_limits.request_count + 1
        END
    RETURNING request_count INTO current_count;

    DELETE FROM public.concierge_rate_limits
    WHERE window_started_at < now() - INTERVAL '2 days';
    RETURN current_count <= p_max_requests;
END;
$$;

REVOKE ALL ON FUNCTION public.allow_concierge_request(TEXT, INTEGER, INTEGER) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.allow_concierge_request(TEXT, INTEGER, INTEGER) TO service_role;

CREATE OR REPLACE FUNCTION public.save_concierge_scenario_version()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF (to_jsonb(NEW) - ARRAY['used_count', 'updated_at', 'version'])
       IS DISTINCT FROM
       (to_jsonb(OLD) - ARRAY['used_count', 'updated_at', 'version']) THEN
        NEW.version := OLD.version + 1;
        NEW.updated_at := now();
        INSERT INTO public.concierge_scenario_versions (scenario_id, version, snapshot, updated_by)
        VALUES (OLD.id, OLD.version, to_jsonb(OLD), NEW.updated_by);
    ELSE
        NEW.version := OLD.version;
        NEW.updated_at := OLD.updated_at;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS concierge_scenario_version_before_update ON public.concierge_scenarios;
CREATE TRIGGER concierge_scenario_version_before_update
    BEFORE UPDATE ON public.concierge_scenarios
    FOR EACH ROW EXECUTE FUNCTION public.save_concierge_scenario_version();

