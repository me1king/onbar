-- Rider-managed profile information for the authenticated rider terminal.
-- Run after DISPATCH_MIGRATION.sql, RIDER_ONBOARDING_SECURITY_MIGRATION.sql,
-- RIDER_TERMINAL_WORKFLOW_MIGRATION.sql, and DELIVERY_ENGINE_AND_BUZZ_MIGRATION.sql.

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.rider_status') IS NULL THEN
    RAISE EXCEPTION 'Rider profile details require public.rider_status.'
      USING HINT = 'Run supabase/DISPATCH_MIGRATION.sql first.';
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.rider_profile_details (
  rider_phone TEXT PRIMARY KEY REFERENCES public.rider_status(rider_phone) ON DELETE CASCADE,
  whatsapp_number TEXT,
  emergency_contact_name TEXT,
  emergency_contact_phone TEXT,
  guarantor_name TEXT,
  guarantor_phone TEXT,
  delivery_zones TEXT[] NOT NULL DEFAULT '{}',
  max_distance_km NUMERIC(5, 1),
  shift_days TEXT[] NOT NULL DEFAULT '{}',
  shift_start_time TIME,
  shift_end_time TIME,
  mpesa_number TEXT,
  mpesa_registered_name TEXT,
  mpesa_name_verified_at TIMESTAMPTZ,
  mpesa_name_verified_by TEXT,
  license_expiry_date DATE,
  insurance_expiry_date DATE,
  age_check_training_completed_at TIMESTAMPTZ,
  rider_agreement_accepted_at TIMESTAMPTZ,
  rider_agreement_version TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT rider_profile_details_delivery_zones_count_check
    CHECK (cardinality(delivery_zones) <= 20),
  CONSTRAINT rider_profile_details_shift_days_check
    CHECK (shift_days <@ ARRAY['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday']::TEXT[]),
  CONSTRAINT rider_profile_details_distance_check
    CHECK (max_distance_km IS NULL OR max_distance_km BETWEEN 1 AND 100)
);

CREATE TABLE IF NOT EXISTS public.rider_profile_audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_phone TEXT NOT NULL REFERENCES public.rider_status(rider_phone) ON DELETE CASCADE,
  actor_type TEXT NOT NULL CHECK (actor_type IN ('rider', 'admin')),
  actor TEXT NOT NULL,
  changed_fields TEXT[] NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS rider_profile_audit_events_phone_created_idx
  ON public.rider_profile_audit_events (rider_phone, created_at DESC);

ALTER TABLE public.rider_profile_details ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rider_profile_audit_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.rider_profile_details, public.rider_profile_audit_events
  FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.rider_profile_details, public.rider_profile_audit_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.rider_profile_audit_events_id_seq TO service_role;

COMMIT;
