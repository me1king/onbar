CREATE OR REPLACE FUNCTION public.save_rider_delivery_zones(
  p_rider_phone TEXT,
  p_zone_ids BIGINT[]
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF coalesce(cardinality(p_zone_ids), 0) > 20 THEN
    RAISE EXCEPTION 'Select no more than 20 delivery zones.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM unnest(coalesce(p_zone_ids, ARRAY[]::BIGINT[])) AS selected(zone_id)
    LEFT JOIN public.delivery_zones AS zone
      ON zone.id = selected.zone_id AND zone.is_active
    WHERE zone.id IS NULL
  ) THEN
    RAISE EXCEPTION 'Choose only active delivery zones.';
  END IF;

  DELETE FROM public.rider_delivery_zones
  WHERE rider_phone = p_rider_phone;
  INSERT INTO public.rider_delivery_zones (rider_phone, zone_id)
  SELECT p_rider_phone, selected.zone_id
  FROM (
    SELECT DISTINCT zone_id
    FROM unnest(coalesce(p_zone_ids, ARRAY[]::BIGINT[])) AS value(zone_id)
  ) AS selected;
END;
$$;

CREATE OR REPLACE FUNCTION public.normalize_kenyan_rider_phone(p_value TEXT)
RETURNS TEXT
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  digits TEXT := regexp_replace(coalesce(p_value, ''), '[^0-9]', '', 'g');
  national TEXT;
BEGIN
  IF left(digits, 3) = '254' THEN
    national := substr(digits, 4);
  ELSIF left(digits, 1) = '0' THEN
    national := substr(digits, 2);
  ELSE
    national := digits;
  END IF;
  IF national ~ '^[17][0-9]{8}$' THEN
    RETURN '254' || national;
  END IF;
  RETURN NULL;
END;
$$;

DO $$
DECLARE
  constraint_row RECORD;
  table_row RECORD;
  delete_action TEXT;
  match_action TEXT;
  deferrable_clause TEXT;
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.rider_status
    WHERE public.normalize_kenyan_rider_phone(rider_phone) IS NULL
  ) THEN
    RAISE EXCEPTION 'Cannot normalize rider phones: rider_status contains an invalid Kenyan number.';
  END IF;
  IF EXISTS (
    SELECT public.normalize_kenyan_rider_phone(rider_phone)
    FROM public.rider_status
    GROUP BY public.normalize_kenyan_rider_phone(rider_phone)
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Cannot normalize rider phones: multiple rider accounts resolve to the same 254 number.';
  END IF;

  IF to_regclass('public.rider_onboarding_progress') IS NOT NULL THEN
    ALTER TABLE public.rider_onboarding_progress
      DROP CONSTRAINT IF EXISTS rider_onboarding_progress_rider_phone_check;
  END IF;
  IF to_regclass('public.merchant_rider_invites') IS NOT NULL THEN
    ALTER TABLE public.merchant_rider_invites
      DROP CONSTRAINT IF EXISTS merchant_rider_invites_rider_phone_check;
  END IF;

  FOR constraint_row IN
    SELECT foreign_key.oid, foreign_key.conrelid, foreign_key.conname,
      foreign_key.confdeltype, foreign_key.confupdtype,
      foreign_key.confmatchtype, foreign_key.condeferrable, foreign_key.condeferred,
      child_attribute.attname AS child_column,
      parent_attribute.attname AS parent_column
    FROM pg_constraint AS foreign_key
    JOIN pg_attribute AS child_attribute
      ON child_attribute.attrelid = foreign_key.conrelid
      AND child_attribute.attnum = foreign_key.conkey[1]
    JOIN pg_attribute AS parent_attribute
      ON parent_attribute.attrelid = foreign_key.confrelid
      AND parent_attribute.attnum = foreign_key.confkey[1]
    WHERE foreign_key.contype = 'f'
      AND foreign_key.confrelid = 'public.rider_status'::regclass
      AND array_length(foreign_key.conkey, 1) = 1
      AND array_length(foreign_key.confkey, 1) = 1
      AND parent_attribute.attname = 'rider_phone'
  LOOP
    IF constraint_row.confupdtype <> 'c' THEN
      delete_action := CASE constraint_row.confdeltype
        WHEN 'r' THEN ' ON DELETE RESTRICT'
        WHEN 'c' THEN ' ON DELETE CASCADE'
        WHEN 'n' THEN ' ON DELETE SET NULL'
        WHEN 'd' THEN ' ON DELETE SET DEFAULT'
        ELSE ''
      END;
      match_action := CASE constraint_row.confmatchtype
        WHEN 'f' THEN ' MATCH FULL'
        WHEN 'p' THEN ' MATCH PARTIAL'
        ELSE ''
      END;
      deferrable_clause := CASE
        WHEN constraint_row.condeferrable AND constraint_row.condeferred
          THEN ' DEFERRABLE INITIALLY DEFERRED'
        WHEN constraint_row.condeferrable
          THEN ' DEFERRABLE INITIALLY IMMEDIATE'
        ELSE ''
      END;
      EXECUTE format(
        'ALTER TABLE %s DROP CONSTRAINT %I',
        constraint_row.conrelid::regclass, constraint_row.conname
      );
      EXECUTE format(
        'ALTER TABLE %s ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES public.rider_status(%I)%s%s ON UPDATE CASCADE%s',
        constraint_row.conrelid::regclass, constraint_row.conname,
        constraint_row.child_column, constraint_row.parent_column,
        match_action, delete_action, deferrable_clause
      );
    END IF;
  END LOOP;

  UPDATE public.rider_status
  SET rider_phone = public.normalize_kenyan_rider_phone(rider_phone)
  WHERE rider_phone IS DISTINCT FROM public.normalize_kenyan_rider_phone(rider_phone);

  FOR table_row IN
    SELECT DISTINCT columns.table_schema, columns.table_name
    FROM information_schema.columns AS columns
    JOIN information_schema.tables AS tables
      ON tables.table_schema = columns.table_schema
      AND tables.table_name = columns.table_name
    WHERE columns.table_schema = 'public'
      AND columns.column_name = 'rider_phone'
      AND tables.table_type = 'BASE TABLE'
  LOOP
    EXECUTE format(
      'UPDATE %I.%I SET rider_phone = public.normalize_kenyan_rider_phone(rider_phone) WHERE public.normalize_kenyan_rider_phone(rider_phone) IS NOT NULL AND rider_phone IS DISTINCT FROM public.normalize_kenyan_rider_phone(rider_phone)',
      table_row.table_schema, table_row.table_name
    );
  END LOOP;

  ALTER TABLE public.rider_status
    DROP CONSTRAINT IF EXISTS rider_status_canonical_phone_check;
  ALTER TABLE public.rider_status
    ADD CONSTRAINT rider_status_canonical_phone_check
    CHECK (rider_phone ~ '^254[17][0-9]{8}$') NOT VALID;
  ALTER TABLE public.rider_status
    VALIDATE CONSTRAINT rider_status_canonical_phone_check;

  IF to_regclass('public.rider_onboarding_progress') IS NOT NULL THEN
    ALTER TABLE public.rider_onboarding_progress
      ADD CONSTRAINT rider_onboarding_progress_rider_phone_check
      CHECK (rider_phone ~ '^254[17][0-9]{8}$');
  END IF;
  IF to_regclass('public.merchant_rider_invites') IS NOT NULL THEN
    ALTER TABLE public.merchant_rider_invites
      ADD CONSTRAINT merchant_rider_invites_rider_phone_check
      CHECK (rider_phone ~ '^254[17][0-9]{8}$');
  END IF;
END;
$$;

