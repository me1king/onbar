CREATE OR REPLACE FUNCTION public.rider_assignment_block_reason(
  p_order_id BIGINT,
  p_rider_phone TEXT
)
RETURNS TEXT
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  order_row public.orders%ROWTYPE;
  rider public.rider_status%ROWTYPE;
  details public.rider_profile_details%ROWTYPE;
  max_distance NUMERIC;
  distance NUMERIC;
  reasons TEXT[];
BEGIN
  SELECT * INTO order_row FROM public.orders WHERE id = p_order_id;
  IF NOT FOUND THEN RETURN 'Order was not found.'; END IF;
  SELECT * INTO rider FROM public.rider_status WHERE rider_phone = p_rider_phone;
  IF NOT FOUND THEN RETURN 'Rider was not found.'; END IF;

  IF rider.status NOT IN ('Idle', 'Delivering') THEN
    RETURN 'Rider is offline.';
  END IF;
  reasons := public.rider_online_block_reasons(p_rider_phone);
  IF cardinality(reasons) > 0 THEN
    RETURN array_to_string(reasons, ' ');
  END IF;

  SELECT * INTO details
  FROM public.rider_profile_details
  WHERE rider_phone = p_rider_phone;
  SELECT policy.max_distance_km INTO max_distance
  FROM public.rider_dispatch_policy AS policy
  WHERE policy.singleton;

  IF order_row.delivery_zone_id IS NULL THEN
    RETURN 'Customer map pin is outside configured delivery zones or is missing.';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.rider_delivery_zones AS rider_zone
    JOIN public.delivery_zones AS zone
      ON zone.id = rider_zone.zone_id AND zone.is_active
    WHERE rider_zone.rider_phone = p_rider_phone
      AND rider_zone.zone_id = order_row.delivery_zone_id
  ) THEN
    RETURN 'Rider is not assigned to the customer delivery zone.';
  END IF;

  distance := public.rider_distance_km(
    rider.last_known_lat, rider.last_known_lng, order_row.latitude, order_row.longitude
  );
  IF distance IS NULL OR distance > least(
    max_distance, coalesce(details.max_distance_km, max_distance)
  ) THEN
    RETURN 'Customer is beyond the rider distance limit.';
  END IF;
  RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.enforce_rider_order_assignment()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  should_check BOOLEAN := TG_OP = 'INSERT';
  block_reason TEXT;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    should_check := NEW.rider_phone IS DISTINCT FROM OLD.rider_phone
      OR (
        NEW.status = 'Dispatched'
        AND OLD.status IS DISTINCT FROM NEW.status
      );
  END IF;

  IF should_check
     AND NEW.rider_phone IS NOT NULL
     AND NEW.status IN ('Dispatched', 'Picked Up', 'Out for Delivery') THEN
    block_reason := public.rider_assignment_block_reason(NEW.id, NEW.rider_phone);
    IF block_reason IS NOT NULL THEN
      RAISE EXCEPTION 'Rider assignment blocked: %', block_reason;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

