CREATE OR REPLACE FUNCTION public.rider_is_within_shift(
  p_days TEXT[],
  p_start TIME,
  p_end TIME,
  p_now TIMESTAMPTZ DEFAULT now()
)
RETURNS BOOLEAN
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  local_now TIMESTAMP;
  local_time TIME;
  today_name TEXT;
  previous_day_name TEXT;
BEGIN
  IF coalesce(cardinality(p_days), 0) = 0 OR p_start IS NULL OR p_end IS NULL OR p_start = p_end THEN
    RETURN false;
  END IF;

  local_now := p_now AT TIME ZONE 'Africa/Nairobi';
  local_time := local_now::TIME;
  today_name := CASE extract(ISODOW FROM local_now)::INTEGER
    WHEN 1 THEN 'Monday'
    WHEN 2 THEN 'Tuesday'
    WHEN 3 THEN 'Wednesday'
    WHEN 4 THEN 'Thursday'
    WHEN 5 THEN 'Friday'
    WHEN 6 THEN 'Saturday'
    ELSE 'Sunday'
  END;
  previous_day_name := CASE extract(ISODOW FROM local_now)::INTEGER
    WHEN 1 THEN 'Sunday'
    WHEN 2 THEN 'Monday'
    WHEN 3 THEN 'Tuesday'
    WHEN 4 THEN 'Wednesday'
    WHEN 5 THEN 'Thursday'
    WHEN 6 THEN 'Friday'
    ELSE 'Saturday'
  END;

  IF p_start < p_end THEN
    RETURN today_name = ANY(p_days) AND local_time >= p_start AND local_time < p_end;
  END IF;
  RETURN (today_name = ANY(p_days) AND local_time >= p_start)
    OR (previous_day_name = ANY(p_days) AND local_time < p_end);
END;
$$;

CREATE OR REPLACE FUNCTION public.rider_online_block_reasons(p_rider_phone TEXT)
RETURNS TEXT[]
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  rider public.rider_status%ROWTYPE;
  details public.rider_profile_details%ROWTYPE;
  max_distance NUMERIC;
  reasons TEXT[] := ARRAY[]::TEXT[];
BEGIN
  SELECT * INTO rider
  FROM public.rider_status
  WHERE rider_phone = p_rider_phone;
  IF NOT FOUND THEN
    RETURN ARRAY['Rider account was not found.'];
  END IF;

  SELECT * INTO details
  FROM public.rider_profile_details
  WHERE rider_phone = p_rider_phone;
  IF NOT FOUND THEN
    RETURN ARRAY['Complete your rider profile before going online.'];
  END IF;

  SELECT policy.max_distance_km INTO max_distance
  FROM public.rider_dispatch_policy AS policy
  WHERE policy.singleton;

  IF rider.verification_status IS DISTINCT FROM 'Verified' THEN
    reasons := array_append(reasons, 'Rider verification is not complete.');
  END IF;
  IF details.license_expiry_date IS NULL
     OR details.license_expiry_date < (now() AT TIME ZONE 'Africa/Nairobi')::DATE
     OR details.license_document_path IS NULL
     OR details.license_document_verified_at IS NULL THEN
    reasons := array_append(reasons, 'A current, admin-verified driving licence is required.');
  END IF;
  IF details.insurance_expiry_date IS NULL
     OR details.insurance_expiry_date < (now() AT TIME ZONE 'Africa/Nairobi')::DATE
     OR details.insurance_document_path IS NULL
     OR details.insurance_document_verified_at IS NULL THEN
    reasons := array_append(reasons, 'Current, admin-verified insurance is required.');
  END IF;
  IF details.mpesa_name_verified_at IS NULL
     OR nullif(trim(details.mpesa_number), '') IS NULL
     OR nullif(trim(details.mpesa_registered_name), '') IS NULL THEN
    reasons := array_append(reasons, 'An admin-verified M-Pesa destination is required.');
  END IF;
  IF nullif(trim(details.emergency_contact_name), '') IS NULL
     OR nullif(trim(details.emergency_contact_phone), '') IS NULL THEN
    reasons := array_append(reasons, 'Add an emergency contact before going online.');
  END IF;
  IF nullif(trim(details.guarantor_name), '') IS NULL
     OR nullif(trim(details.guarantor_phone), '') IS NULL THEN
    reasons := array_append(reasons, 'Add a guarantor before going online.');
  END IF;
  IF coalesce(cardinality(details.shift_days), 0) = 0
     OR details.shift_start_time IS NULL
     OR details.shift_end_time IS NULL
     OR NOT public.rider_is_within_shift(
       details.shift_days, details.shift_start_time, details.shift_end_time, now()
     ) THEN
    reasons := array_append(reasons, 'You are outside your saved shift in Nairobi time.');
  END IF;
  IF rider.last_known_lat IS NULL
     OR rider.last_known_lng IS NULL
     OR rider.last_known_lat NOT BETWEEN -90 AND 90
     OR rider.last_known_lng NOT BETWEEN -180 AND 180
     OR rider.location_updated_at IS NULL
     OR rider.location_updated_at < now() - INTERVAL '5 minutes'
     OR rider.location_updated_at > now() THEN
    reasons := array_append(reasons, 'A fresh GPS location from the last five minutes is required.');
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.rider_delivery_zones AS rider_zone
    JOIN public.delivery_zones AS zone ON zone.id = rider_zone.zone_id AND zone.is_active
    WHERE rider_zone.rider_phone = p_rider_phone
  ) THEN
    reasons := array_append(reasons, 'Select at least one active delivery zone.');
  END IF;
  RETURN reasons;
END;
$$;

