CREATE OR REPLACE FUNCTION public.rider_distance_km(
  p_latitude_a NUMERIC,
  p_longitude_a NUMERIC,
  p_latitude_b NUMERIC,
  p_longitude_b NUMERIC
)
RETURNS NUMERIC
LANGUAGE SQL
IMMUTABLE
STRICT
PARALLEL SAFE
SET search_path = ''
AS $$
  SELECT 6371 * 2 * asin(sqrt(
    power(sin(radians(p_latitude_b - p_latitude_a) / 2), 2)
    + cos(radians(p_latitude_a)) * cos(radians(p_latitude_b))
    * power(sin(radians(p_longitude_b - p_longitude_a) / 2), 2)
  ));
$$;

CREATE OR REPLACE FUNCTION public.find_delivery_zone(
  p_latitude NUMERIC,
  p_longitude NUMERIC
)
RETURNS BIGINT
LANGUAGE SQL
STABLE
SET search_path = ''
AS $$
  SELECT zone.id
  FROM public.delivery_zones AS zone
  WHERE zone.is_active
    AND public.rider_distance_km(
      p_latitude, p_longitude, zone.center_latitude, zone.center_longitude
    ) <= zone.radius_km
  ORDER BY public.rider_distance_km(
    p_latitude, p_longitude, zone.center_latitude, zone.center_longitude
  ), zone.id
  LIMIT 1;
$$;

