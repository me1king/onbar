CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'general',
    description TEXT,
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.vendor_profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    zone TEXT NOT NULL DEFAULT 'Westlands',
    latitude NUMERIC(10, 7) NOT NULL,
    longitude NUMERIC(10, 7) NOT NULL,
    delivery_radius_km NUMERIC(5, 2) NOT NULL DEFAULT 4,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'suspended')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.vendor_products (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    vendor_id UUID NOT NULL REFERENCES public.vendor_profiles(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    vendor_price NUMERIC(12, 2) NOT NULL CHECK (vendor_price >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    is_selected BOOLEAN NOT NULL DEFAULT false,
    is_reachable BOOLEAN NOT NULL DEFAULT true,
    delivery_eta_minutes INTEGER NOT NULL DEFAULT 30,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (vendor_id, product_id)
);

CREATE TABLE IF NOT EXISTS public.pricing_rules (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    vendor_id UUID REFERENCES public.vendor_profiles(id) ON DELETE CASCADE,
    zone TEXT NOT NULL DEFAULT 'Westlands',
    rule_type TEXT NOT NULL DEFAULT 'percent' CHECK (rule_type IN ('percent', 'fixed', 'tiered')),
    markup_value NUMERIC(12, 2) NOT NULL DEFAULT 12,
    min_margin NUMERIC(12, 2) NOT NULL DEFAULT 40,
    round_to INTEGER NOT NULL DEFAULT 10 CHECK (round_to > 0),
    max_price NUMERIC(12, 2),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.vendor_product_visibility (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    vendor_id UUID NOT NULL REFERENCES public.vendor_profiles(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    customer_lat NUMERIC(10, 7) NOT NULL,
    customer_lng NUMERIC(10, 7) NOT NULL,
    distance_km NUMERIC(8, 2) NOT NULL DEFAULT 0,
    is_visible BOOLEAN NOT NULL DEFAULT false,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (vendor_id, product_id, customer_lat, customer_lng)
);

CREATE TABLE IF NOT EXISTS public.rider_profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    phone TEXT NOT NULL UNIQUE,
    vehicle_type TEXT NOT NULL DEFAULT 'motorbike' CHECK (vehicle_type IN ('motorbike', 'bicycle', 'van')),
    rating NUMERIC(3, 2) NOT NULL DEFAULT 5.0,
    acceptance_rate NUMERIC(5, 2) NOT NULL DEFAULT 100,
    recent_trips INTEGER NOT NULL DEFAULT 0,
    base_pay NUMERIC(12, 2) NOT NULL DEFAULT 650,
    status TEXT NOT NULL DEFAULT 'online' CHECK (status IN ('online', 'offline', 'paused')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rider_dispatch_scores (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    rider_id UUID NOT NULL REFERENCES public.rider_profiles(id) ON DELETE CASCADE,
    order_id BIGINT,
    distance_km NUMERIC(6, 2) NOT NULL DEFAULT 0,
    score NUMERIC(5, 2) NOT NULL DEFAULT 0,
    payout_estimate NUMERIC(12, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rider_payouts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    rider_id UUID NOT NULL REFERENCES public.rider_profiles(id) ON DELETE CASCADE,
    order_id BIGINT,
    base_pay NUMERIC(12, 2) NOT NULL DEFAULT 0,
    distance_pay NUMERIC(12, 2) NOT NULL DEFAULT 0,
    bonus NUMERIC(12, 2) NOT NULL DEFAULT 0,
    tip NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_paid NUMERIC(12, 2) NOT NULL DEFAULT 0,
    paid_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'failed'))
);

CREATE INDEX IF NOT EXISTS products_name_idx ON public.products (name);
CREATE INDEX IF NOT EXISTS vendor_products_vendor_idx ON public.vendor_products (vendor_id, is_selected);
CREATE INDEX IF NOT EXISTS pricing_rules_vendor_idx ON public.pricing_rules (vendor_id, is_active);
CREATE INDEX IF NOT EXISTS vendor_product_visibility_vendor_idx ON public.vendor_product_visibility (vendor_id, is_visible);
CREATE INDEX IF NOT EXISTS rider_dispatch_scores_rider_idx ON public.rider_dispatch_scores (rider_id, created_at DESC);
CREATE INDEX IF NOT EXISTS rider_payouts_rider_idx ON public.rider_payouts (rider_id, paid_at DESC);

CREATE OR REPLACE FUNCTION public.compute_customer_price(
    p_vendor_price NUMERIC,
    p_rule_type TEXT DEFAULT 'percent',
    p_markup_value NUMERIC DEFAULT 12,
    p_min_margin NUMERIC DEFAULT 40,
    p_round_to INTEGER DEFAULT 10,
    p_max_price NUMERIC DEFAULT NULL
)
RETURNS NUMERIC
LANGUAGE plpgsql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
DECLARE
    calculated_price NUMERIC := COALESCE(p_vendor_price, 0);
    margin_amount NUMERIC := 0;
BEGIN
    IF p_vendor_price IS NULL OR p_vendor_price <= 0 THEN
        RETURN 0;
    END IF;

    IF p_rule_type = 'fixed' THEN
        calculated_price := p_vendor_price + COALESCE(p_markup_value, 0);
    ELSIF p_rule_type = 'tiered' THEN
        calculated_price := p_vendor_price + GREATEST(COALESCE(p_min_margin, 0), COALESCE(p_markup_value, 0));
    ELSE
        calculated_price := p_vendor_price * (1 + COALESCE(p_markup_value, 0) / 100);
    END IF;

    margin_amount := GREATEST(calculated_price - p_vendor_price, COALESCE(p_min_margin, 0));
    calculated_price := COALESCE(p_vendor_price, 0) + margin_amount;

    IF COALESCE(p_round_to, 1) > 0 THEN
        calculated_price := CEIL(calculated_price / p_round_to) * p_round_to;
    END IF;

    IF p_max_price IS NOT NULL AND calculated_price > p_max_price THEN
        RETURN p_max_price;
    END IF;

    RETURN calculated_price;
END;
$$;

CREATE OR REPLACE FUNCTION public.visible_vendor_products_for_customer(
    p_customer_lat NUMERIC,
    p_customer_lng NUMERIC,
    p_radius_km NUMERIC DEFAULT 4
)
RETURNS TABLE (
    vendor_id UUID,
    vendor_name TEXT,
    product_id BIGINT,
    product_name TEXT,
    customer_price NUMERIC,
    profit_per_item NUMERIC,
    distance_km NUMERIC,
    stock INTEGER,
    is_visible BOOLEAN
)
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
SELECT
    vp.vendor_id,
    vendor.name AS vendor_name,
    vp.product_id,
    product.name AS product_name,
    public.compute_customer_price(vp.vendor_price, 'percent', 12, 40, 10, 850) AS customer_price,
    public.compute_customer_price(vp.vendor_price, 'percent', 12, 40, 10, 850) - vp.vendor_price AS profit_per_item,
    ROUND(
        CAST(
            111.32 * sqrt(
                power(vendor.latitude - p_customer_lat, 2) +
                power((vendor.longitude - p_customer_lng) * cos(radians(p_customer_lat)), 2)
            ) AS NUMERIC
        ),
        2
    ) AS distance_km,
    vp.stock,
    vp.stock > 0 AND vp.is_selected AND vp.is_reachable AND vendor.status = 'active' AND (
        111.32 * sqrt(
            power(vendor.latitude - p_customer_lat, 2) +
            power((vendor.longitude - p_customer_lng) * cos(radians(p_customer_lat)), 2)
        ) <= COALESCE(p_radius_km, 4)
    ) AS is_visible
FROM public.vendor_products vp
JOIN public.vendor_profiles vendor ON vendor.id = vp.vendor_id
JOIN public.products product ON product.id = vp.product_id
WHERE vp.stock > 0
ORDER BY distance_km ASC, product.name ASC;
$$;

CREATE OR REPLACE FUNCTION public.score_dispatch_rider(
    p_rating NUMERIC,
    p_acceptance_rate NUMERIC,
    p_distance_km NUMERIC,
    p_recent_trips INTEGER,
    p_vehicle_type TEXT DEFAULT 'motorbike'
)
RETURNS NUMERIC
LANGUAGE plpgsql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
DECLARE
    score NUMERIC := 0;
BEGIN
    score := 55 + (COALESCE(p_rating, 0) * 12) + (COALESCE(p_acceptance_rate, 0) * 0.4) + (LEAST(COALESCE(p_recent_trips, 0), 30) * 1.2);
    score := score + CASE COALESCE(p_vehicle_type, 'motorbike')
        WHEN 'motorbike' THEN 12
        WHEN 'van' THEN 8
        ELSE 4
    END;
    score := score - (COALESCE(p_distance_km, 0) * 6);
    RETURN LEAST(100, GREATEST(0, score));
END;
$$;

CREATE OR REPLACE FUNCTION public.calculate_rider_payout(
    p_base_pay NUMERIC,
    p_distance_km NUMERIC,
    p_bonus NUMERIC,
    p_tip NUMERIC
)
RETURNS NUMERIC
LANGUAGE plpgsql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
BEGIN
    RETURN GREATEST(0, COALESCE(p_base_pay, 0) + (COALESCE(p_distance_km, 0) * 30) + COALESCE(p_bonus, 0) + COALESCE(p_tip, 0));
END;
$$;
