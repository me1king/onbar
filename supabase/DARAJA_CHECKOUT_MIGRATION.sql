-- Direct Safaricom Daraja M-Pesa Express checkout and encrypted credential storage.
-- Apply after FINAL_ESTABLISHMENT_SQL.sql and PAYHERO_DRINK_ORDERS_MIGRATION.sql.
-- Re-run MERCHANT_OPERATIONS_MIGRATION.sql and COD_RIDER_DISPATCH_MIGRATION.sql
-- first if your deployment has not applied the latest versions.

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.orders') IS NULL
     OR to_regclass('public.payment_confirmations') IS NULL THEN
    RAISE EXCEPTION 'Daraja checkout requires orders and payment confirmation tables.'
      USING HINT = 'Run FINAL_ESTABLISHMENT_SQL.sql first.';
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.payment_provider_credentials (
  provider TEXT PRIMARY KEY CHECK (provider IN ('daraja')),
  encrypted_credentials TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.payment_provider_credentials ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.payment_provider_credentials FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.payment_provider_credentials TO service_role;

ALTER TABLE public.payment_confirmations
  DROP CONSTRAINT IF EXISTS payment_confirmations_provider_check;
ALTER TABLE public.payment_confirmations
  ADD CONSTRAINT payment_confirmations_provider_check
  CHECK (provider IN ('Paystack', 'PayHero', 'Daraja'));

CREATE TABLE IF NOT EXISTS public.daraja_order_payment_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES public.orders(id) ON DELETE CASCADE,
  external_reference TEXT NOT NULL UNIQUE,
  callback_token_hash TEXT NOT NULL UNIQUE CHECK (callback_token_hash ~ '^[0-9a-f]{64}$'),
  merchant_request_id TEXT,
  checkout_request_id TEXT UNIQUE,
  amount_ksh BIGINT NOT NULL CHECK (amount_ksh > 0),
  phone_e164 TEXT NOT NULL CHECK (phone_e164 ~ '^\+254[17][0-9]{8}$'),
  mpesa_receipt TEXT UNIQUE,
  status TEXT NOT NULL DEFAULT 'initializing'
    CHECK (status IN ('initializing', 'queued', 'unknown', 'paid', 'failed', 'review')),
  error_message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS daraja_order_payments_status_idx
  ON public.daraja_order_payment_attempts (status, updated_at DESC);
ALTER TABLE public.daraja_order_payment_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.daraja_order_payment_attempts FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.daraja_order_payment_attempts TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.daraja_order_payment_attempts_id_seq TO service_role;

-- Extend existing dispatch/allocation guards without weakening their requirement
-- for a verified payment confirmation and exact order amount.
DO $$
DECLARE
  routine RECORD;
  original_definition TEXT;
  updated_definition TEXT;
BEGIN
  FOR routine IN
    SELECT p.oid
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
      AND p.prokind IN ('f', 'p')
      AND p.prosrc ILIKE '%payhero%'
      AND p.prosrc ILIKE '%paystack%'
  LOOP
    original_definition := pg_get_functiondef(routine.oid);
    updated_definition := original_definition;
    updated_definition := replace(
      updated_definition,
      'IN (''paystack'', ''payhero'')',
      'IN (''paystack'', ''payhero'', ''daraja'')'
    );
    updated_definition := replace(
      updated_definition,
      'NOT IN (''paystack'', ''payhero'')',
      'NOT IN (''paystack'', ''payhero'', ''daraja'')'
    );
    updated_definition := replace(
      updated_definition,
      'WHEN lower($4) = ''payhero'' THEN ''PayHero''',
      'WHEN lower($4) = ''payhero'' THEN ''PayHero'' WHEN lower($4) = ''daraja'' THEN ''Daraja'''
    );
    updated_definition := replace(
      updated_definition,
      'WHEN lower(target_order.payment_method) = ''payhero'' THEN ''PayHero''',
      'WHEN lower(target_order.payment_method) = ''payhero'' THEN ''PayHero'' WHEN lower(target_order.payment_method) = ''daraja'' THEN ''Daraja'''
    );
    updated_definition := replace(
      updated_definition,
      'WHEN lower(coalesce(target_order.payment_method, '''')) = ''payhero'' THEN ''PayHero''',
      'WHEN lower(coalesce(target_order.payment_method, '''')) = ''payhero'' THEN ''PayHero'' WHEN lower(coalesce(target_order.payment_method, '''')) = ''daraja'' THEN ''Daraja'''
    );
    updated_definition := replace(
      updated_definition,
      'WHEN lower(coalesce(parent_order.payment_method, '''')) = ''payhero'' THEN ''PayHero''',
      'WHEN lower(coalesce(parent_order.payment_method, '''')) = ''payhero'' THEN ''PayHero'' WHEN lower(coalesce(parent_order.payment_method, '''')) = ''daraja'' THEN ''Daraja'''
    );
    updated_definition := replace(
      updated_definition,
      'WHEN lower(coalesce(order_row.payment_method, '''')) = ''payhero'' THEN ''PayHero''',
      'WHEN lower(coalesce(order_row.payment_method, '''')) = ''payhero'' THEN ''PayHero'' WHEN lower(coalesce(order_row.payment_method, '''')) = ''daraja'' THEN ''Daraja'''
    );
    updated_definition := replace(
      updated_definition,
      'WHEN lower(NEW.payment_method) = ''payhero'' THEN ''PayHero''',
      'WHEN lower(NEW.payment_method) = ''payhero'' THEN ''PayHero'' WHEN lower(NEW.payment_method) = ''daraja'' THEN ''Daraja'''
    );
    updated_definition := replace(
      updated_definition,
      'Online dispatch is limited to server-verified Paystack or PayHero orders.',
      'Online dispatch is limited to server-verified Paystack, PayHero, or Daraja orders.'
    );
    IF updated_definition IS DISTINCT FROM original_definition THEN
      EXECUTE updated_definition;
    END IF;
  END LOOP;
END;
$$;

COMMIT;
NOTIFY pgrst, 'reload schema';
