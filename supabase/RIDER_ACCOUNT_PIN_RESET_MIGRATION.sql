-- Secure rider approval PIN hashing and admin PIN resets.
-- Run after DISPATCH_MIGRATION.sql and SECURITY_HARDENING_MIGRATION.sql.

BEGIN;

CREATE TABLE IF NOT EXISTS public.rider_account_security_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_phone TEXT NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('approved', 'pin_reset')),
  actor TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS rider_account_security_events_phone_idx
  ON public.rider_account_security_events (rider_phone, created_at DESC);

ALTER TABLE public.rider_account_security_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.rider_account_security_events FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.rider_account_security_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.rider_account_security_events_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.admin_set_rider_pin(
  phone_input TEXT,
  pin_input TEXT,
  action_input TEXT,
  actor_input TEXT
)
RETURNS TABLE(rider_phone TEXT, rider_name TEXT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  changed_phone TEXT;
  changed_name TEXT;
BEGIN
  IF phone_input IS NULL OR length(trim(phone_input)) NOT BETWEEN 1 AND 50
     OR pin_input !~ '^[0-9]{4}$'
     OR action_input NOT IN ('approved', 'pin_reset')
     OR nullif(trim(actor_input), '') IS NULL THEN
    RAISE EXCEPTION 'Invalid rider PIN operation.';
  END IF;
  IF action_input = 'pin_reset' AND pin_input <> '0000' THEN
    RAISE EXCEPTION 'A rider PIN reset must use the approved temporary PIN.';
  END IF;

  UPDATE public.rider_status AS rider
  SET pin = crypt(pin_input, gen_salt('bf')),
      verification_status = CASE
        WHEN action_input = 'approved' THEN 'Verified'
        ELSE rider.verification_status
      END,
      updated_at = now()
  WHERE rider.rider_phone = phone_input
    AND (
      action_input = 'approved'
      OR rider.verification_status = 'Verified'
    )
  RETURNING rider.rider_phone, rider.rider_name
  INTO changed_phone, changed_name;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  INSERT INTO public.rider_account_security_events (rider_phone, action, actor)
  VALUES (changed_phone, action_input, trim(actor_input));

  RETURN QUERY SELECT changed_phone, changed_name;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_set_rider_pin(TEXT, TEXT, TEXT, TEXT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.admin_set_rider_pin(TEXT, TEXT, TEXT, TEXT)
  TO service_role;

NOTIFY pgrst, 'reload schema';

COMMIT;
