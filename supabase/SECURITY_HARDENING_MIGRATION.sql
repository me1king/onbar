-- Hardens customer data access and enables atomic, server-only rewards and rider login.

DO $$
DECLARE
    missing_tables TEXT;
BEGIN
    SELECT string_agg(required.table_name, ', ')
    INTO missing_tables
    FROM (VALUES
        ('public.profiles'),
        ('public.staff'),
        ('public.orders'),
        ('public.order_items'),
        ('public.rider_status'),
        ('public.financial_ledger'),
        ('public.analytics_events'),
        ('public.reviews')
    ) AS required(table_name)
    WHERE to_regclass(required.table_name) IS NULL;

    IF missing_tables IS NOT NULL THEN
        RAISE EXCEPTION 'Security hardening requires core tables: %.', missing_tables
            USING HINT = 'Install the core, dispatch, and operational schemas before this migration.';
    END IF;
END;
$$;

