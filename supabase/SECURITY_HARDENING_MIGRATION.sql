CREATE OR REPLACE FUNCTION public.award_member_loyalty_points(
    profile_id_input UUID,
    points_input INTEGER,
    description_input TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
BEGIN
    IF points_input < 0 OR points_input > 10000 OR char_length(description_input) > 500 THEN
        RAISE EXCEPTION 'Invalid loyalty award.';
    END IF;
    UPDATE public.profiles
    SET loyalty_points = coalesce(loyalty_points, 0) + points_input,
        updated_at = now()
    WHERE id = profile_id_input;
    IF NOT FOUND THEN RAISE EXCEPTION 'Member profile not found.'; END IF;
    INSERT INTO public.loyalty_ledger(profile_id, amount, description)
    VALUES (profile_id_input, points_input, description_input);
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_daily_member_reward(
    profile_id_input UUID,
    reward_type_input TEXT,
    reward_label_input TEXT,
    reward_value_input INTEGER,
    points_input INTEGER
)
RETURNS TABLE(next_claim_at TIMESTAMPTZ)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
    last_claim TIMESTAMPTZ;
BEGIN
    IF reward_type_input NOT IN ('spin', 'box')
       OR reward_value_input < 0 OR reward_value_input > 10000
       OR points_input < 0 OR points_input > reward_value_input THEN
        RAISE EXCEPTION 'Invalid reward claim.';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended(profile_id_input::TEXT || ':' || reward_type_input, 0));
    SELECT max(created_at) INTO last_claim
    FROM public.daily_rewards_log
    WHERE user_id = profile_id_input AND reward_type = reward_type_input;
    IF last_claim IS NOT NULL AND last_claim > now() - interval '24 hours' THEN
        RAISE EXCEPTION 'Please wait % hours before your next claim.',
            ceil(extract(epoch FROM (last_claim + interval '24 hours' - now())) / 3600)::INTEGER;
    END IF;

    INSERT INTO public.daily_rewards_log(user_id, reward_type, reward_label, reward_value)
    VALUES (profile_id_input, reward_type_input, reward_label_input, reward_value_input);
    IF points_input > 0 THEN
        PERFORM public.award_member_loyalty_points(
            profile_id_input, points_input, format('Daily %s reward: %s', reward_type_input, reward_label_input)
        );
    END IF;
    RETURN QUERY SELECT now() + interval '24 hours';
END;
$$;

CREATE OR REPLACE FUNCTION public.award_photo_review_reward(
    review_id_input BIGINT,
    profile_id_input UUID
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM public.reviews
        WHERE id = review_id_input
          AND user_id = profile_id_input
          AND jsonb_array_length(coalesce(to_jsonb(photo_urls), '[]'::JSONB)) > 0
    ) THEN
        RAISE EXCEPTION 'An eligible photo review belonging to this account was not found.';
    END IF;

    INSERT INTO public.photo_review_rewards(review_id, profile_id)
    VALUES (review_id_input, profile_id_input);
    PERFORM public.award_member_loyalty_points(
        profile_id_input, 50, format('Photo review reward: review %s', review_id_input)
    );
    RETURN 50;
EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION 'This photo review has already been rewarded.';
END;
$$;

