CREATE OR REPLACE FUNCTION public.allow_rider_login_attempt(identity_input TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
    identity_digest TEXT := encode(digest(identity_input, 'sha256'), 'hex');
    failed_count INTEGER;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtextextended(identity_digest, 0));
    DELETE FROM public.rider_login_attempts WHERE attempted_at < now() - interval '1 day';
    SELECT count(*) INTO failed_count
    FROM public.rider_login_attempts
    WHERE identity_hash = identity_digest
      AND attempted_at > now() - interval '15 minutes';
    IF failed_count >= 5 THEN RETURN false; END IF;
    INSERT INTO public.rider_login_attempts(identity_hash) VALUES (identity_digest);
    RETURN true;
END;
$$;

CREATE OR REPLACE FUNCTION public.verify_rider_pin(
    phone_variants_input TEXT[],
    pin_input TEXT
)
RETURNS TABLE(id BIGINT, rider_name TEXT, rider_phone TEXT, status TEXT, verification_status TEXT)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
    SELECT r.id, r.rider_name, r.rider_phone, r.status, r.verification_status
    FROM public.rider_status r
    WHERE r.rider_phone = ANY(phone_variants_input)
      AND r.pin = crypt(pin_input, r.pin)
      AND r.verification_status = 'Verified'
    LIMIT 1
$$;

