 -- Durable order lifecycle history and atomic admin status transitions.
-- Run after FINAL_ESTABLISHMENT_SQL.sql and DISPATCH_MIGRATION.sql.

BEGIN;

DO $$
BEGIN
    IF to_regclass('public.orders') IS NULL OR to_regclass('public.rider_status') IS NULL THEN
        RAISE EXCEPTION 'Order flow migration requires public.orders and public.rider_status.'
            USING HINT = 'Run FINAL_ESTABLISHMENT_SQL.sql and DISPATCH_MIGRATION.sql first.';
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.order_status_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
    from_status TEXT,
    to_status TEXT NOT NULL,
    actor_type TEXT NOT NULL CHECK (actor_type IN ('system', 'payment', 'admin', 'rider')),
    actor_id TEXT,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS order_status_events_order_created_idx
    ON public.order_status_events (order_id, created_at, id);
CREATE INDEX IF NOT EXISTS order_status_events_created_idx
    ON public.order_status_events (created_at DESC, id DESC);

ALTER TABLE public.order_status_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.order_status_events FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.order_status_events TO service_role;

CREATE OR REPLACE FUNCTION public.capture_order_status_event()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    configured_actor TEXT := current_setting('app.order_actor_type', true);
    actor_kind TEXT;
    actor_identity TEXT;
    previous_status TEXT;
    event_reason TEXT := nullif(current_setting('app.order_transition_reason', true), '');
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.status IS NOT DISTINCT FROM OLD.status THEN
            RETURN NEW;
        END IF;
        previous_status := OLD.status;
        IF configured_actor IN ('admin', 'payment', 'rider', 'system') THEN
            actor_kind := configured_actor;
        ELSIF NEW.rider_phone IS DISTINCT FROM OLD.rider_phone THEN
            actor_kind := 'admin';
        ELSIF NEW.status IN ('Paid', 'Payment Failed', 'Refunded') THEN
            actor_kind := 'payment';
        ELSIF NEW.status IN ('Picked Up', 'Out for Delivery', 'Delivered') AND NEW.rider_phone IS NOT NULL THEN
            actor_kind := 'rider';
        ELSE
            actor_kind := 'system';
        END IF;
    ELSE
        previous_status := NULL;
        actor_kind := CASE
            WHEN configured_actor IN ('admin', 'payment', 'rider', 'system') THEN configured_actor
            WHEN NEW.status IN ('Paid', 'Payment Failed', 'Refunded') THEN 'payment'
            ELSE 'system'
        END;
    END IF;

    actor_identity := nullif(current_setting('app.order_actor_id', true), '');
    IF actor_identity IS NULL AND actor_kind = 'rider' THEN
        actor_identity := NEW.rider_phone;
    END IF;

    INSERT INTO public.order_status_events (
        order_id, from_status, to_status, actor_type, actor_id, reason
    )
    VALUES (
        NEW.id,
        previous_status,
        coalesce(NEW.status, 'Unknown'),
        actor_kind,
        actor_identity,
        event_reason
    );
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS orders_capture_status_event ON public.orders;
CREATE TRIGGER orders_capture_status_event
    AFTER INSERT OR UPDATE ON public.orders
    FOR EACH ROW
    EXECUTE FUNCTION public.capture_order_status_event();

CREATE OR REPLACE FUNCTION public.order_status_transition_allowed(
    current_state TEXT,
    next_state TEXT
)
RETURNS BOOLEAN
LANGUAGE SQL
IMMUTABLE
SET search_path = pg_catalog
AS $$
    SELECT CASE current_state
        WHEN 'Created' THEN next_state IN ('Payment Pending', 'Cancelled')
        WHEN 'Pending' THEN next_state IN ('Paid', 'Payment Failed', 'Cancelled')
        WHEN 'Payment Pending' THEN next_state IN ('Paid', 'Payment Failed', 'Cancelled')
        WHEN 'Confirmed' THEN next_state IN ('Processing', 'Cancelled')
        WHEN 'Paid' THEN next_state IN ('Stock Reserved', 'Cancelled', 'Refunded', 'Dispatched')
        WHEN 'Stock Reserved' THEN next_state IN ('Supplier Confirmed', 'Processing', 'Cancelled', 'Refunded')
        WHEN 'Supplier Confirmed' THEN next_state IN ('Processing', 'Cancelled', 'Refunded')
        WHEN 'Processing' THEN next_state IN ('Packed', 'Cancelled', 'Refunded')
        WHEN 'Packed' THEN next_state IN ('Dispatched', 'Cancelled', 'Refunded')
        WHEN 'Dispatched' THEN next_state IN ('Picked Up', 'Out for Delivery', 'Delivered', 'Cancelled', 'Refunded')
        WHEN 'Picked Up' THEN next_state IN ('Out for Delivery', 'Delivered', 'Returned')
        WHEN 'Out for Delivery' THEN next_state IN ('Delivered', 'Returned', 'Cancelled')
        WHEN 'Delivered' THEN next_state IN ('Completed', 'Warranty', 'Returned')
        WHEN 'Completed' THEN next_state IN ('Warranty', 'Returned')
        WHEN 'Payment Failed' THEN next_state IN ('Payment Pending', 'Cancelled')
        WHEN 'Warranty' THEN next_state IN ('Processing', 'Completed')
        WHEN 'Returned' THEN next_state IN ('Refunded', 'Stock Reserved')
        ELSE false
    END;
$$;

REVOKE ALL ON FUNCTION public.order_status_transition_allowed(TEXT, TEXT)
    FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.transition_order_states(
    order_ids_input BIGINT[],
    new_state_input TEXT,
    reason_input TEXT,
    admin_email_input TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    target_order RECORD;
    requested_count INTEGER;
    found_count INTEGER;
    changed_ids BIGINT[] := ARRAY[]::BIGINT[];
BEGIN
    IF order_ids_input IS NULL OR cardinality(order_ids_input) < 1 OR cardinality(order_ids_input) > 100 THEN
        RAISE EXCEPTION 'Select between 1 and 100 orders.';
    END IF;
    IF cardinality(order_ids_input) <> (
        SELECT count(DISTINCT requested_id)::INTEGER FROM unnest(order_ids_input) AS requested(requested_id)
    ) THEN
        RAISE EXCEPTION 'An order may only be selected once.';
    END IF;
    IF new_state_input NOT IN (
        'Created', 'Pending', 'Payment Pending', 'Confirmed', 'Paid', 'Stock Reserved', 'Supplier Confirmed',
        'Processing', 'Packed', 'Dispatched', 'Picked Up', 'Out for Delivery', 'Delivered',
        'Completed', 'Cancelled', 'Payment Failed', 'Refunded', 'Warranty', 'Returned'
    ) THEN
        RAISE EXCEPTION 'Unknown order status.';
    END IF;
    IF new_state_input IN (
        'Paid', 'Payment Failed', 'Refunded', 'Dispatched', 'Picked Up',
        'Out for Delivery', 'Delivered'
    ) THEN
        RAISE EXCEPTION '% must be changed through the payment, dispatch, or rider workflow.', new_state_input;
    END IF;
    IF nullif(trim(admin_email_input), '') IS NULL THEN
        RAISE EXCEPTION 'An administrator identity is required.';
    END IF;

    PERFORM order_row.id
    FROM public.orders AS order_row
    WHERE order_row.id = ANY(order_ids_input)
    ORDER BY order_row.id
    FOR UPDATE;

    SELECT count(*)::INTEGER INTO requested_count FROM unnest(order_ids_input);
    SELECT count(*)::INTEGER INTO found_count
    FROM public.orders AS order_row
    WHERE order_row.id = ANY(order_ids_input);
    IF found_count <> requested_count THEN
        RAISE EXCEPTION 'One or more selected orders could not be found.';
    END IF;

    FOR target_order IN
        SELECT order_row.id, order_row.status
        FROM public.orders AS order_row
        WHERE order_row.id = ANY(order_ids_input)
        ORDER BY order_row.id
    LOOP
        IF target_order.status IS DISTINCT FROM new_state_input
           AND NOT public.order_status_transition_allowed(target_order.status, new_state_input) THEN
            RAISE EXCEPTION 'Cannot move order #% from % to %.',
                target_order.id, coalesce(target_order.status, 'Unknown'), new_state_input;
        END IF;
    END LOOP;

    PERFORM set_config('app.order_actor_type', 'admin', true);
    PERFORM set_config('app.order_actor_id', trim(admin_email_input), true);
    PERFORM set_config('app.order_transition_reason', coalesce(nullif(trim(reason_input), ''), 'Admin status update'), true);

    FOR target_order IN
        SELECT order_row.id, order_row.status
        FROM public.orders AS order_row
        WHERE order_row.id = ANY(order_ids_input)
        ORDER BY order_row.id
    LOOP
        IF target_order.status IS DISTINCT FROM new_state_input THEN
            UPDATE public.orders SET status = new_state_input WHERE id = target_order.id;
            changed_ids := array_append(changed_ids, target_order.id);
        END IF;
    END LOOP;

    RETURN jsonb_build_object('updated', cardinality(changed_ids), 'order_ids', changed_ids);
END;
$$;

CREATE OR REPLACE FUNCTION public.transition_order_state(
    order_id_input BIGINT,
    new_state_input TEXT,
    reason_input TEXT,
    admin_email_input TEXT
)
RETURNS JSONB
LANGUAGE SQL
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
    SELECT public.transition_order_states(
        ARRAY[order_id_input],
        new_state_input,
        reason_input,
        admin_email_input
    );
$$;

REVOKE ALL ON FUNCTION public.transition_order_states(BIGINT[], TEXT, TEXT, TEXT)
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.transition_order_state(BIGINT, TEXT, TEXT, TEXT)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.transition_order_states(BIGINT[], TEXT, TEXT, TEXT) TO service_role;
GRANT EXECUTE ON FUNCTION public.transition_order_state(BIGINT, TEXT, TEXT, TEXT) TO service_role;

COMMIT;
