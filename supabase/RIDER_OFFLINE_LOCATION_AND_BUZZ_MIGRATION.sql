-- Apply after DISPATCH_MIGRATION.sql and RIDER_ORDER_ALERTS_MIGRATION.sql.
-- Adds a private snapshot of the last known rider location at offline time
-- and a distinct alert step for admin-initiated rider buzzes.
BEGIN;

CREATE TABLE IF NOT EXISTS public.rider_offline_location_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_phone TEXT NOT NULL REFERENCES public.rider_status(rider_phone) ON DELETE CASCADE,
  latitude NUMERIC,
  longitude NUMERIC,
  location_recorded_at TIMESTAMPTZ,
  went_offline_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT rider_offline_location_coordinates_check CHECK (
    (latitude IS NULL) = (longitude IS NULL)
    AND (
      latitude IS NULL
      OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
    )
  )
);

CREATE INDEX IF NOT EXISTS rider_offline_location_events_phone_idx
  ON public.rider_offline_location_events (rider_phone, went_offline_at DESC);

ALTER TABLE public.rider_offline_location_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.rider_offline_location_events FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.rider_offline_location_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.rider_offline_location_events_id_seq TO service_role;

ALTER TABLE public.rider_order_alert_log
  DROP CONSTRAINT IF EXISTS rider_order_alert_log_step_check;
ALTER TABLE public.rider_order_alert_log
  ADD CONSTRAINT rider_order_alert_log_step_check
  CHECK (step IN ('assignment', 'sms_10s', 'buzz'));

CREATE OR REPLACE FUNCTION public.claim_rider_order_alert(
  p_order_id BIGINT,
  p_rider_phone TEXT,
  p_channel TEXT,
  p_step TEXT,
  p_recipient_key TEXT
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  claimed_id UUID;
BEGIN
  IF p_channel NOT IN ('push', 'sms')
     OR p_step NOT IN ('assignment', 'sms_10s', 'buzz')
     OR char_length(coalesce(p_recipient_key, '')) NOT BETWEEN 1 AND 256 THEN
    RAISE EXCEPTION 'Invalid rider alert claim.';
  END IF;

  INSERT INTO public.rider_order_alert_log (
    order_id, rider_phone, channel, step, recipient_key, status, sent_at
  ) VALUES (
    p_order_id, p_rider_phone, p_channel, p_step, p_recipient_key, 'sending', now()
  )
  ON CONFLICT (order_id, rider_phone, channel, step, recipient_key)
  DO UPDATE SET
    status = 'sending',
    error = NULL,
    sent_at = now(),
    attempt_count = public.rider_order_alert_log.attempt_count + 1
  WHERE public.rider_order_alert_log.status = 'failed'
     OR (
       public.rider_order_alert_log.status = 'sending'
       AND public.rider_order_alert_log.sent_at < now() - INTERVAL '2 minutes'
     )
  RETURNING id INTO claimed_id;

  RETURN claimed_id;
END;
$$;

REVOKE ALL ON FUNCTION public.claim_rider_order_alert(BIGINT, TEXT, TEXT, TEXT, TEXT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_rider_order_alert(BIGINT, TEXT, TEXT, TEXT, TEXT)
  TO service_role;

CREATE OR REPLACE FUNCTION public.set_rider_online_status(
  p_rider_phone TEXT,
  p_online BOOLEAN
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  target_rider public.rider_status%ROWTYPE;
  changed_at TIMESTAMPTZ := now();
BEGIN
  IF p_online IS NULL THEN
    RETURN jsonb_build_object('success', false, 'code', 'INVALID_STATUS', 'error', 'A valid online status is required.');
  END IF;

  SELECT * INTO target_rider
  FROM public.rider_status
  WHERE rider_phone = p_rider_phone
  FOR UPDATE;
  IF NOT FOUND OR target_rider.verification_status <> 'Verified' THEN
    RETURN jsonb_build_object('success', false, 'code', 'RIDER_NOT_VERIFIED', 'error', 'Only verified riders can change online status.');
  END IF;

  IF NOT p_online THEN
    IF EXISTS (
      SELECT 1 FROM public.orders
      WHERE rider_phone = p_rider_phone
        AND status IN ('Dispatched', 'Picked Up', 'Out for Delivery')
    ) THEN
      RETURN jsonb_build_object(
        'success', false,
        'code', 'ACTIVE_DELIVERY',
        'error', 'Complete or hand off active deliveries before going offline.'
      );
    END IF;

    IF target_rider.status IN ('Idle', 'Delivering') THEN
      INSERT INTO public.rider_offline_location_events (
        rider_phone, latitude, longitude, location_recorded_at, went_offline_at
      ) VALUES (
        p_rider_phone,
        CASE
          WHEN target_rider.last_known_lat BETWEEN -90 AND 90
            AND target_rider.last_known_lng BETWEEN -180 AND 180
          THEN target_rider.last_known_lat
          ELSE NULL
        END,
        CASE
          WHEN target_rider.last_known_lat BETWEEN -90 AND 90
            AND target_rider.last_known_lng BETWEEN -180 AND 180
          THEN target_rider.last_known_lng
          ELSE NULL
        END,
        CASE
          WHEN target_rider.last_known_lat BETWEEN -90 AND 90
            AND target_rider.last_known_lng BETWEEN -180 AND 180
          THEN target_rider.location_updated_at
          ELSE NULL
        END,
        changed_at
      );
    END IF;
  END IF;

  UPDATE public.rider_status
  SET status = CASE WHEN p_online THEN 'Idle' ELSE 'Offline' END,
      online_since = CASE WHEN p_online THEN changed_at ELSE NULL END,
      updated_at = changed_at
  WHERE rider_phone = p_rider_phone;

  RETURN jsonb_build_object(
    'success', true,
    'status', CASE WHEN p_online THEN 'Idle' ELSE 'Offline' END,
    'updated_at', changed_at
  );
END;
$$;

REVOKE ALL ON FUNCTION public.set_rider_online_status(TEXT, BOOLEAN)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.set_rider_online_status(TEXT, BOOLEAN) TO service_role;

NOTIFY pgrst, 'reload schema';
COMMIT;
