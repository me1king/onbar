-- Customer-level channel preferences and idempotent order notification delivery records.

CREATE TABLE IF NOT EXISTS public.customer_notification_preferences (
    channel_key TEXT PRIMARY KEY,
    customer_email TEXT,
    customer_phone TEXT,
    channels TEXT[] NOT NULL DEFAULT ARRAY['email']::TEXT[],
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT customer_notification_preferences_channels_check
        CHECK (channels <@ ARRAY['email', 'whatsapp', 'sms']::TEXT[])
);

CREATE INDEX IF NOT EXISTS customer_notification_preferences_email_idx
    ON public.customer_notification_preferences (lower(customer_email))
    WHERE customer_email IS NOT NULL;

ALTER TABLE public.customer_notification_preferences ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.customer_notification_preferences FROM anon, authenticated;
GRANT ALL ON public.customer_notification_preferences TO service_role;

CREATE TABLE IF NOT EXISTS public.customer_notification_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    notification_status TEXT NOT NULL,
    channel TEXT NOT NULL CHECK (channel IN ('email', 'whatsapp', 'sms')),
    delivery_status TEXT NOT NULL DEFAULT 'sending'
        CHECK (delivery_status IN ('sending', 'sent', 'failed')),
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (order_id, notification_status, channel)
);

ALTER TABLE public.customer_notification_deliveries
    DROP CONSTRAINT IF EXISTS customer_notification_deliveries_notification_status_check;
ALTER TABLE public.customer_notification_deliveries
    ADD CONSTRAINT customer_notification_deliveries_notification_status_check
        CHECK (notification_status IN ('Paid', 'Dispatched', 'Picked Up', 'Out for Delivery', 'Delivered'));

CREATE INDEX IF NOT EXISTS customer_notification_deliveries_order_idx
    ON public.customer_notification_deliveries (order_id, created_at DESC);

ALTER TABLE public.customer_notification_deliveries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.customer_notification_deliveries FROM anon, authenticated;
GRANT ALL ON public.customer_notification_deliveries TO service_role;

NOTIFY pgrst, 'reload schema';
