CREATE OR REPLACE FUNCTION public.respond_to_rider_order_offer(
  p_order_id BIGINT,
  p_rider_phone TEXT,
  p_response TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  target_order public.orders%ROWTYPE;
  final_response TEXT := p_response;
  final_status TEXT;
  responded_at_value TIMESTAMPTZ := now();
BEGIN
  IF p_response NOT IN ('accepted', 'declined') THEN
    RAISE EXCEPTION 'Offer response must be accepted or declined.';
  END IF;

  SELECT * INTO target_order
  FROM public.orders
  WHERE id = p_order_id
  FOR UPDATE;

  IF NOT FOUND OR target_order.rider_phone IS DISTINCT FROM p_rider_phone THEN
    RAISE EXCEPTION 'This offer is not assigned to this rider.';
  END IF;
  IF target_order.status <> 'Dispatched' THEN
    RAISE EXCEPTION 'This offer is no longer available.';
  END IF;
  IF target_order.rider_offer_status = 'accepted' AND p_response = 'accepted' THEN
    RETURN jsonb_build_object('response', 'accepted', 'status', target_order.status);
  END IF;
  IF target_order.rider_offer_status <> 'pending' THEN
    RAISE EXCEPTION 'This offer has already been answered.';
  END IF;

  IF target_order.rider_offer_expires_at IS NULL
     OR target_order.rider_offer_expires_at <= now() THEN
    final_response := 'expired';
  END IF;

  IF final_response = 'accepted' THEN
    UPDATE public.orders
    SET rider_offer_status = 'accepted',
        rider_offer_responded_at = responded_at_value,
        updated_at = responded_at_value
    WHERE id = p_order_id;
    UPDATE public.rider_status
    SET status = 'Delivering',
        updated_at = responded_at_value
    WHERE rider_phone = p_rider_phone;
    final_status := target_order.status;
  ELSE
    UPDATE public.orders
    SET status = 'Paid',
        rider_offer_status = final_response,
        rider_offer_responded_at = responded_at_value,
        rider_name = NULL,
        rider_phone = NULL,
        delivery_pin = NULL,
        customer_id_checked_at = NULL,
        updated_at = responded_at_value
    WHERE id = p_order_id;
    final_status := 'Paid';

    UPDATE public.rider_status
    SET status = CASE
          WHEN EXISTS (
            SELECT 1 FROM public.orders active_order
            WHERE active_order.rider_phone = p_rider_phone
              AND active_order.status IN ('Dispatched', 'Picked Up', 'Out for Delivery')
          ) THEN 'Delivering'
          ELSE 'Idle'
        END,
        updated_at = responded_at_value
    WHERE rider_phone = p_rider_phone;
  END IF;

  INSERT INTO public.rider_offer_events (
    order_id, rider_phone, response, expires_at, responded_at
  ) VALUES (
    p_order_id, p_rider_phone, final_response,
    target_order.rider_offer_expires_at, responded_at_value
  );

  RETURN jsonb_build_object('response', final_response, 'status', final_status);
END;
$$;

REVOKE ALL ON FUNCTION public.respond_to_rider_order_offer(BIGINT, TEXT, TEXT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.respond_to_rider_order_offer(BIGINT, TEXT, TEXT)
  TO service_role;

