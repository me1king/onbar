CREATE OR REPLACE FUNCTION public.claim_rider_arrival_notification(
  p_order_id BIGINT,
  p_rider_phone TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  claimed_order_id BIGINT;
BEGIN
  INSERT INTO public.rider_arrival_notifications (order_id, rider_phone, status)
  VALUES (p_order_id, p_rider_phone, 'sending')
  ON CONFLICT (order_id) DO UPDATE SET
    rider_phone = EXCLUDED.rider_phone,
    status = 'sending',
    provider_message_id = NULL,
    error_message = NULL,
    attempt_count = public.rider_arrival_notifications.attempt_count + 1,
    updated_at = now()
  WHERE public.rider_arrival_notifications.status = 'failed'
     OR (
       public.rider_arrival_notifications.status = 'sending'
       AND public.rider_arrival_notifications.updated_at < now() - INTERVAL '2 minutes'
     )
  RETURNING order_id INTO claimed_order_id;
  RETURN claimed_order_id IS NOT NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.claim_rider_arrival_notification(BIGINT, TEXT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_rider_arrival_notification(BIGINT, TEXT)
  TO service_role;

CREATE OR REPLACE FUNCTION public.prepare_rider_order_offer()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NEW.status = 'Dispatched'
     AND NEW.rider_phone IS NOT NULL
     AND (
       OLD.status IS DISTINCT FROM NEW.status
       OR OLD.rider_phone IS DISTINCT FROM NEW.rider_phone
     ) THEN
    NEW.rider_offer_status := 'pending';
    NEW.rider_offer_expires_at := now() + INTERVAL '30 seconds';
    NEW.rider_offer_responded_at := NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS orders_prepare_rider_offer ON public.orders;
CREATE TRIGGER orders_prepare_rider_offer
  BEFORE UPDATE OF status, rider_phone ON public.orders
  FOR EACH ROW
  EXECUTE FUNCTION public.prepare_rider_order_offer();

CREATE OR REPLACE FUNCTION public.log_rider_order_offer()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NEW.status = 'Dispatched'
     AND NEW.rider_phone IS NOT NULL
     AND (
       OLD.status IS DISTINCT FROM NEW.status
       OR OLD.rider_phone IS DISTINCT FROM NEW.rider_phone
     ) THEN
    INSERT INTO public.rider_offer_events (order_id, rider_phone, response, expires_at)
    VALUES (NEW.id, NEW.rider_phone, 'pending', NEW.rider_offer_expires_at);
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS orders_log_rider_offer ON public.orders;
CREATE TRIGGER orders_log_rider_offer
  AFTER UPDATE OF status, rider_phone ON public.orders
  FOR EACH ROW
  EXECUTE FUNCTION public.log_rider_order_offer();

