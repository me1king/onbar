-- PayHero M-Pesa checkout and verified payment records for drink-delivery orders.
-- Apply after FINAL_ESTABLISHMENT_SQL.sql, MERCHANT_OPERATIONS_MIGRATION.sql,
-- and DISPATCH_MIGRATION.sql. Re-run the updated merchant and dispatch
-- migrations before this one so their allocation/dispatch rules recognize PayHero.

BEGIN;

DO $$
BEGIN
    IF to_regclass('public.orders') IS NULL
       OR to_regclass('public.payment_confirmations') IS NULL THEN
        RAISE EXCEPTION 'PayHero drink payments require orders and payment confirmation tables.'
            USING HINT = 'Run supabase/FINAL_ESTABLISHMENT_SQL.sql and supabase/DISPATCH_MIGRATION.sql first.';
    END IF;
END;
$$;

ALTER TABLE public.payment_confirmations
    DROP CONSTRAINT IF EXISTS payment_confirmations_provider_check;
ALTER TABLE public.payment_confirmations
    ADD CONSTRAINT payment_confirmations_provider_check
    CHECK (provider IN ('Paystack', 'PayHero'));

CREATE TABLE IF NOT EXISTS public.payhero_order_payment_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES public.orders(id) ON DELETE CASCADE,
    external_reference TEXT NOT NULL UNIQUE,
    payhero_reference TEXT UNIQUE,
    checkout_request_id TEXT UNIQUE,
    callback_secret_hash TEXT NOT NULL CHECK (callback_secret_hash ~ '^[0-9a-f]{64}$'),
    amount_kobo BIGINT NOT NULL CHECK (amount_kobo > 0),
    status TEXT NOT NULL DEFAULT 'initializing'
        CHECK (status IN ('initializing', 'queued', 'unknown', 'paid', 'failed', 'review')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS payhero_order_payments_status_idx
    ON public.payhero_order_payment_attempts (status, updated_at DESC);

ALTER TABLE public.payhero_order_payment_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.payhero_order_payment_attempts FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.payhero_order_payment_attempts TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.payhero_order_payment_attempts_id_seq TO service_role;

COMMIT;
NOTIFY pgrst, 'reload schema';
