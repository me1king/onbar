-- Private customer-management records for the Admin/Lord CRM.
-- Run after FINAL_ESTABLISHMENT_SQL.sql.

BEGIN;

DO $$
BEGIN
    IF to_regclass('public.profiles') IS NULL
       OR to_regclass('public.orders') IS NULL
       OR to_regclass('public.user_consent') IS NULL
       OR to_regclass('public.user_notifications') IS NULL THEN
        RAISE EXCEPTION 'Customer CRM prerequisites are missing.'
            USING HINT = 'Run FINAL_ESTABLISHMENT_SQL.sql first.';
    END IF;
END;
$$;

ALTER TABLE public.user_consent
    ADD COLUMN IF NOT EXISTS in_app_marketing BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.customer_crm_records (
    phone_key TEXT PRIMARY KEY,
    profile_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    full_name TEXT,
    email TEXT,
    address TEXT,
    birth_date DATE,
    tags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT customer_crm_records_phone_key_length CHECK (length(phone_key) BETWEEN 7 AND 15)
);

CREATE TABLE IF NOT EXISTS public.customer_crm_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_key TEXT NOT NULL REFERENCES public.customer_crm_records(phone_key) ON DELETE CASCADE,
    body TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 5000),
    author_email TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.customer_crm_followups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_key TEXT NOT NULL REFERENCES public.customer_crm_records(phone_key) ON DELETE CASCADE,
    title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
    description TEXT,
    due_at TIMESTAMPTZ NOT NULL,
    priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('low', 'normal', 'high')),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'completed')),
    created_by TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.customer_crm_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_key TEXT NOT NULL REFERENCES public.customer_crm_records(phone_key) ON DELETE CASCADE,
    actor_email TEXT NOT NULL,
    action TEXT NOT NULL CHECK (action IN ('profile_updated', 'tags_updated', 'followup_created', 'followup_completed')),
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS customer_crm_notes_phone_created_idx
    ON public.customer_crm_notes (phone_key, created_at DESC);
CREATE INDEX IF NOT EXISTS customer_crm_followups_phone_due_idx
    ON public.customer_crm_followups (phone_key, due_at DESC);
CREATE INDEX IF NOT EXISTS customer_crm_followups_open_due_idx
    ON public.customer_crm_followups (due_at)
    WHERE status = 'open';
CREATE INDEX IF NOT EXISTS customer_crm_audit_phone_created_idx
    ON public.customer_crm_audit (phone_key, created_at DESC);

ALTER TABLE public.customer_crm_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customer_crm_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customer_crm_followups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customer_crm_audit ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.customer_crm_records, public.customer_crm_notes,
    public.customer_crm_followups, public.customer_crm_audit FROM anon, authenticated;
GRANT ALL ON public.customer_crm_records, public.customer_crm_notes,
    public.customer_crm_followups, public.customer_crm_audit TO service_role;

DO $$
BEGIN
    IF to_regclass('public.customer_crm_notes_id_seq') IS NOT NULL THEN
        REVOKE ALL ON SEQUENCE public.customer_crm_notes_id_seq FROM anon, authenticated;
        GRANT ALL ON SEQUENCE public.customer_crm_notes_id_seq TO service_role;
    END IF;
    IF to_regclass('public.customer_crm_followups_id_seq') IS NOT NULL THEN
        REVOKE ALL ON SEQUENCE public.customer_crm_followups_id_seq FROM anon, authenticated;
        GRANT ALL ON SEQUENCE public.customer_crm_followups_id_seq TO service_role;
    END IF;
    IF to_regclass('public.customer_crm_audit_id_seq') IS NOT NULL THEN
        REVOKE ALL ON SEQUENCE public.customer_crm_audit_id_seq FROM anon, authenticated;
        GRANT ALL ON SEQUENCE public.customer_crm_audit_id_seq TO service_role;
    END IF;
END;
$$;

COMMIT;
