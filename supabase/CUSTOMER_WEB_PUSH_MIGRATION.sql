-- Apply after CUSTOMER_NOTIFICATION_AUTOMATION_MIGRATION.sql.
-- PWA push subscriptions require an authenticated opt-in and are only readable by service_role.

ALTER TABLE public.orders
    ADD COLUMN IF NOT EXISTS notification_in_app_opt_in BOOLEAN NOT NULL DEFAULT true,
    ADD COLUMN IF NOT EXISTS notification_whatsapp_opt_in BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS notification_sms_opt_in BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS notification_email_opt_in BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.customer_push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    endpoint TEXT NOT NULL UNIQUE,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL,
    consented_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS customer_push_subscriptions_user_idx
    ON public.customer_push_subscriptions (user_id);

ALTER TABLE public.customer_push_subscriptions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.customer_push_subscriptions FROM anon, authenticated;
GRANT ALL ON public.customer_push_subscriptions TO service_role;

ALTER TABLE public.customer_notification_preferences
    DROP CONSTRAINT IF EXISTS customer_notification_preferences_channels_check;
ALTER TABLE public.customer_notification_preferences
    ADD CONSTRAINT customer_notification_preferences_channels_check
        CHECK (channels <@ ARRAY['email', 'whatsapp', 'sms', 'push']::TEXT[]);

ALTER TABLE public.customer_notification_deliveries
    DROP CONSTRAINT IF EXISTS customer_notification_deliveries_channel_check;
ALTER TABLE public.customer_notification_deliveries
    ADD CONSTRAINT customer_notification_deliveries_channel_check
        CHECK (channel IN ('email', 'whatsapp', 'sms', 'push'));

ALTER TABLE public.customer_notification_deliveries
    DROP CONSTRAINT IF EXISTS customer_notification_deliveries_notification_status_check;
ALTER TABLE public.customer_notification_deliveries
    ADD CONSTRAINT customer_notification_deliveries_notification_status_check
        CHECK (notification_status IN ('Pending', 'Payment Failed', 'Paid', 'Dispatched', 'Picked Up', 'Out for Delivery', 'Delivered'));

NOTIFY pgrst, 'reload schema';
